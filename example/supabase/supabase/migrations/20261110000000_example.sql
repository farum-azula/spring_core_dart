-- The project of the example: a table with row-level security, a database
-- function, the table Realtime reports, and a bucket with policies. A part
-- of the migration of the starter's own tests
-- (spring_boot_starter_supabase/test/stack/supabase/migrations), with the
-- same names.
--
-- Every grant is written out: a project no longer exposes new tables to
-- the API roles by itself, and an older one exposes them to `anon` too.

-- ---------------------------------------------------------------- todos
-- A user reads and writes only their rows: the owner of a new row is
-- whoever inserts it (auth.uid() of the caller's token), over the REST
-- API (the app) and over SQL with spring.supabase.db.rls: user (the
-- server).

create table public.todos (
  id bigint generated by default as identity primary key,
  title text not null,
  list_id text not null,
  done boolean not null default false,
  priority text not null default 'low',
  created_at timestamptz,
  version integer,
  owner uuid not null default auth.uid()
);

alter table public.todos enable row level security;

create policy example_own_todos on public.todos
  for all to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid()));

revoke all on public.todos from anon;
grant select, insert, update, delete on public.todos
  to authenticated, service_role;

-- ------------------------------------------------------------ functions
-- `Todos.closeAll` (@Procedure('close_all')): the rows it closes are the
-- caller's, since it runs with the caller's rights.

create function public.close_all(list_id text) returns integer
language sql
set search_path = ''
as $$
  with closed as (
    update public.todos set done = true
    where todos.list_id = close_all.list_id and not done
    returning 1
  )
  select count(*)::integer from closed
$$;

revoke all on function public.close_all(text) from public, anon;
grant execute on function public.close_all(text)
  to authenticated, service_role;

-- ------------------------------------------------------------- Realtime
-- A table is reported only when it is in this publication: the app's
-- live list (`watchByListId`).

do $$
begin
  if not exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    create publication supabase_realtime;
  end if;
end
$$;

alter publication supabase_realtime add table public.todos;

-- -------------------------------------------------------------- Storage
-- The bucket of `Avatars` (@StorageBucket('avatars')): a user reads and
-- writes only under the folder named after their id (`<auth.uid()>/...`).

insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

create policy example_avatars_read on storage.objects
  for select to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy example_avatars_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy example_avatars_update on storage.objects
  for update to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy example_avatars_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

-- ------------------------------------------------------------- SQL path
-- spring.supabase.db.rls: user becomes `authenticated` or `anon` on the
-- connection of SUPABASE_DB_URL: its user must be a member of both. In a
-- project `postgres` is; this only makes sure, and never fails the
-- migration.

do $$
begin
  execute format('grant anon, authenticated to %I', current_user);
exception when others then
  raise notice 'anon and authenticated not granted to %: %',
    current_user, sqlerrm;
end
$$;
