/// The SQL of PostgreSQL: its column types, identity columns, row locks,
/// the way it describes tables, and its SQL states as data access
/// exceptions.
///
/// How values are stored:
///
/// - `int` as `BIGINT` (a Dart `int` is 64 bits); `bool` as `BOOLEAN`;
/// - `double` and `num` as `DOUBLE PRECISION`;
/// - `String` and enums (by name) as `TEXT`;
/// - `DateTime` as `TIMESTAMPTZ`, always the instant in UTC;
/// - `Uint8List` and `List<int>` as `BYTEA`;
/// - `BigInt` as `NUMERIC` (sent as text, read as text);
/// - a `@Json` property as `JSONB` (or `JSON` with `binary: false`): sent
///   as text with a cast, read as text or as the driver decoded it.
///
/// An id the database generates is `BIGINT GENERATED BY DEFAULT AS
/// IDENTITY`; the key comes back through `RETURNING`. Inserting an id
/// yourself does not move the identity's sequence: mix both and the
/// sequence runs into the ids you wrote (`setval` fixes it).
///
/// A `@Lock` query appends `FOR UPDATE` or `FOR SHARE`, with `NOWAIT` for a
/// zero timeout and `SKIP LOCKED`; a longer timeout is `SET LOCAL
/// lock_timeout` before the query. A lock not had in time is a
/// `CannotAcquireLockException`, a lost deadlock a
/// `DeadlockLoserDataAccessException`, a serialization failure a
/// `CannotSerializeTransactionException`.
///
/// `ignoreCase` uses `lower()`, which folds the letters the database's
/// locale knows (`en_US.UTF-8`: `Ä` and `ä`; the `C` locale: ASCII only).
///
/// Spring (Java): `org.springframework.data.relational.core.dialect.
/// PostgresDialect` with the error codes of
/// `SQLErrorCodeSQLExceptionTranslator` for PostgreSQL.
final class PostgresDialect extends SqlDialect {
  /// The dialect of PostgreSQL.
  const PostgresDialect();

  /// The key of the advisory lock the migrations hold.
  static const _migrationLockKey = 4207119845;

  @override
  String get name => 'postgresql';

  @override
  bool get supportsForwardForeignKeys => false;

  @override
  String limitOffset(int? limit, int? offset) => [
    if (limit != null) 'LIMIT $limit',
    if (offset != null) 'OFFSET $offset',
  ].join(' ');

  /// The protocol counts the parameters of a statement in 16 bits.
  @override
  int? get maxBoundParameters => 65535;

  /// `= any(?)` / `<> all(?)`: a list of any length is one parameter (the
  /// server infers the array's type from the column).
  @override
  String? arrayMembership(
    String column, {
    required bool ignoreCase,
    required bool negate,
  }) {
    final operator = negate ? '<> all' : '= any';
    if (!ignoreCase) {
      return '$column $operator(?)';
    }
    return '${lower(column)} $operator'
        '(array(select ${lower('element')} '
        'from unnest(cast(? as text[])) as element))';
  }

  /// The driver writes an array of booleans, of numbers, of texts or of
  /// instants, all of one kind (it tells the kind from the elements); a
  /// `BigInt` goes as its text, as a single one does. It has no array of
  /// bytes, nor of values of several kinds: those get a marker each.
  @override
  bool bindsAsArray(Iterable<Object?> values) {
    Type? kind;
    for (final value in values) {
      final sent = switch (toDatabase(value)) {
        null => null,
        bool() => bool,
        num() => num,
        String() => String,
        DateTime() => DateTime,
        _ => Object,
      };
      if (sent == Object || (sent != null && (kind ??= sent) != sent)) {
        return false;
      }
    }
    return true;
  }

  @override
  bool get supportsFunctions => true;

  /// `select * from "name"("argument" => ?, ...)`: named notation, so the
  /// order of the arguments does not matter and one with a default may be
  /// left out.
  @override
  String functionCall(String name, List<String> arguments) =>
      'select * from ${name.split('.').map(quote).join('.')}'
      '(${arguments.map((argument) => '${quote(argument)} => ?').join(', ')})';

  @override
  LockStrategy get lockStrategy => LockStrategy.rowLocks;

  @override
  String lockClause(
    LockMode mode, {
    Duration? timeout,
    bool skipLocked = false,
  }) => [
    'FOR',
    if (mode == LockMode.pessimisticWrite) 'UPDATE' else 'SHARE',
    // The server refuses both words together; skipping is the stronger ask.
    if (skipLocked) 'SKIP LOCKED' else if (timeout == Duration.zero) 'NOWAIT',
  ].join(' ');

  @override
  String? lockTimeoutStatement(Duration timeout) {
    // 0 would switch the timeout off.
    final millis = timeout.inMilliseconds < 1 ? 1 : timeout.inMilliseconds;
    return "SET LOCAL lock_timeout = '${millis}ms'";
  }

  @override
  String identityColumn(TypeInfo<Object?> type) =>
      'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';

  @override
  Set<Isolation> get isolationLevels => Isolation.values.toSet();

  @override
  String? get migrationLock => 'SELECT pg_advisory_lock($_migrationLockKey)';

  @override
  String? get migrationUnlock =>
      'SELECT pg_advisory_unlock($_migrationLockKey)';

  @override
  String dropTableStatement(
    String table, {
    String? schema,
    bool referenced = false,
  }) =>
      'DROP TABLE IF EXISTS ${this.table(table, schema)}'
      '${referenced ? ' CASCADE' : ''}';

  // --------------------------------------------------------------- schema

  // The test for the schema named, else the connection's.
  static String _schemaTest(String? schema, String column) =>
      schema == null ? '$column = current_schema()' : '$column = ?';

  static List<Object?> _parameters(String table, String? schema) => [
    table,
    ?schema,
  ];

  /// Reads `information_schema.columns` (type as `data_type`, with the
  /// length of a `character varying`) and the primary key.
  @override
  Future<List<ColumnInfo>?> describeTable(
    JdbcConnection connection,
    String table, [
    String? schema,
  ]) async {
    final columns = await connection.query(
      'SELECT column_name, data_type, character_maximum_length, '
      'is_nullable, column_default, is_identity '
      'FROM information_schema.columns '
      'WHERE table_name = ? AND ${_schemaTest(schema, 'table_schema')} '
      'ORDER BY ordinal_position',
      _parameters(table, schema),
    );
    if (columns.isEmpty) {
      return const [];
    }
    final keys = await connection.query(
      'SELECT kcu.column_name '
      'FROM information_schema.table_constraints tc '
      'JOIN information_schema.key_column_usage kcu '
      'ON kcu.constraint_name = tc.constraint_name '
      'AND kcu.constraint_schema = tc.constraint_schema '
      'AND kcu.table_name = tc.table_name '
      "WHERE tc.constraint_type = 'PRIMARY KEY' "
      'AND tc.table_name = ? AND ${_schemaTest(schema, 'tc.table_schema')}',
      _parameters(table, schema),
    );
    final primary = {for (final row in keys.rows) row.values.first! as String};
    return [
      for (final row in columns.rows)
        ColumnInfo(
          name: row['column_name']! as String,
          type: _declared(row),
          notNull: row['is_nullable'] == 'NO',
          defaultValue:
              (row['column_default'] as String?) ??
              (row['is_identity'] == 'YES' ? 'identity' : null),
          primaryKey: primary.contains(row['column_name']),
        ),
    ];
  }

  static String _declared(JdbcRow row) {
    final type = row['data_type']! as String;
    final length = row['character_maximum_length'];
    return length == null ? type : '$type($length)';
  }

  /// Reads the foreign keys of one column from `pg_constraint`.
  @override
  Future<List<ForeignKeyInfo>?> describeForeignKeys(
    JdbcConnection connection,
    String table, [
    String? schema,
  ]) async {
    final result = await connection.query(
      'SELECT a.attname::text AS from_column, p.relname::text AS parent, '
      'pa.attname::text AS to_column, c.confdeltype::text AS on_delete '
      'FROM pg_constraint c '
      'JOIN pg_class t ON t.oid = c.conrelid '
      'JOIN pg_namespace n ON n.oid = t.relnamespace '
      'JOIN pg_class p ON p.oid = c.confrelid '
      'JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = c.conkey[1] '
      'JOIN pg_attribute pa ON pa.attrelid = p.oid '
      'AND pa.attnum = c.confkey[1] '
      "WHERE c.contype = 'f' AND array_length(c.conkey, 1) = 1 "
      'AND t.relname = ? AND ${_schemaTest(schema, 'n.nspname')}',
      _parameters(table, schema),
    );
    return [
      for (final row in result.rows)
        ForeignKeyInfo(
          column: row['from_column']! as String,
          parentTable: row['parent']! as String,
          parentColumn: row['to_column'] as String?,
          onDelete: switch (row['on_delete']) {
            'a' => OnDeleteAction.noAction,
            'r' => OnDeleteAction.restrict,
            'c' => OnDeleteAction.cascade,
            'n' => OnDeleteAction.setNull,
            'd' => OnDeleteAction.setDefault,
            _ => null,
          },
        ),
    ];
  }

  /// Reads the unique indexes of the table (the primary key and the
  /// `UNIQUE` constraints make one each) that are neither partial nor on
  /// an expression.
  @override
  Future<List<UniqueInfo>?> describeUniqueKeys(
    JdbcConnection connection,
    String table, [
    String? schema,
  ]) async {
    final result = await connection.query(
      'SELECT i.relname::text AS index_name, a.attname::text AS column_name '
      'FROM pg_index x '
      'JOIN pg_class t ON t.oid = x.indrelid '
      'JOIN pg_namespace n ON n.oid = t.relnamespace '
      'JOIN pg_class i ON i.oid = x.indexrelid '
      'CROSS JOIN LATERAL unnest(x.indkey::int2[]) '
      'WITH ORDINALITY AS k(attnum, position) '
      'JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum '
      'WHERE x.indisunique AND x.indpred IS NULL AND x.indexprs IS NULL '
      'AND t.relname = ? AND ${_schemaTest(schema, 'n.nspname')} '
      'ORDER BY i.relname, k.position',
      _parameters(table, schema),
    );
    final byIndex = <String, List<String>>{};
    for (final row in result.rows) {
      (byIndex[row['index_name']! as String] ??= []).add(
        row['column_name']! as String,
      );
    }
    return [
      for (final entry in byIndex.entries)
        UniqueInfo(entry.value, name: entry.key),
    ];
  }

  @override
  Future<List<String>?> listTables(JdbcConnection connection) async {
    final result = await connection.query(
      'SELECT table_name FROM information_schema.tables '
      "WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' "
      'ORDER BY table_name',
    );
    return [for (final row in result.rows) row.values.first! as String];
  }

  // ---------------------------------------------------------------- types

  /// A list of simple values (texts, numbers, booleans, instants) is an
  /// array column (`text[]`, `double precision[]`), which the application
  /// creates: the driver binds a list as an array and reads one back, and
  /// each element is converted as a single value is ([toDatabase],
  /// [fromDatabase]). A `Set` and a `Map` are not, and neither is a list
  /// of bytes (`List<Uint8List>`): the driver sends no array of them.
  ///
  /// A `List<BigInt>` wants a `bigint[]` or a `text[]` column: the driver
  /// reads no `numeric[]`.
  @override
  bool storesCollection(TypeInfo<Object?> type) =>
      type is ListType<Object?> &&
      !const {null, _Kind.bytes}.contains(_Kind.of(type.element));

  @override
  String? columnType(TypeInfo<Object?> type) => switch (_Kind.of(type)) {
    _Kind.integer => 'BIGINT',
    _Kind.real => 'DOUBLE PRECISION',
    _Kind.text => 'TEXT',
    _Kind.boolean => 'BOOLEAN',
    _Kind.timestamp => 'TIMESTAMPTZ',
    _Kind.bytes => 'BYTEA',
    _Kind.big => 'NUMERIC',
    null => null,
  };

  /// What `information_schema` says a column is (`bigint`, `integer`,
  /// `double precision`, `character varying(40)`, `timestamp with time
  /// zone`...), against what the property asks: any integer width for an
  /// `int`, `real` or `numeric` for a `double`, any text type for a
  /// `String` or an enum, any date or timestamp for a `DateTime`.
  @override
  bool columnFits(String declared, TypeInfo<Object?> type) {
    final wanted = _Kind.of(type);
    if (wanted == null) {
      return false;
    }
    final found = declared.toLowerCase().replaceFirst(RegExp(r'\(.*\)$'), '');
    return switch (wanted) {
      _Kind.integer => const {'smallint', 'integer', 'bigint'}.contains(found),
      _Kind.real => const {
        'double precision',
        'real',
        'numeric',
      }.contains(found),
      _Kind.text => const {
        'text',
        'character varying',
        'character',
        'uuid',
        'citext',
      }.contains(found),
      _Kind.boolean => found == 'boolean',
      _Kind.timestamp => found == 'date' || found.startsWith('timestamp'),
      _Kind.bytes => found == 'bytea',
      _Kind.big => const {'numeric', 'bigint', 'text'}.contains(found),
    };
  }

  // ----------------------------------------------------------------- json

  /// `JSONB` (binary: decomposed, indexable, key order not kept) or
  /// `JSON` (the text as written): bound as text with a cast, read as the
  /// driver gives it (decoded already, or the text).
  @override
  JsonStorage jsonStorage(Json json) => json.binary
      ? const _PostgresJsonStorage('JSONB')
      : const _PostgresJsonStorage('JSON');

  // --------------------------------------------------------------- values

  /// A `DateTime` in UTC, a `BigInt` as its text, a `List<int>` as bytes
  /// (the `bytea` of a property declared so); any other list is an array,
  /// whose elements are converted as single values are.
  @override
  Object? toDatabase(Object? value) => switch (value) {
    DateTime() => value.toUtc(),
    BigInt() => value.toString(),
    Uint8List() => value,
    List<int>() => Uint8List.fromList(value),
    List<Object?>() => [for (final element in value) toDatabase(element)],
    _ => value,
  };

  @override
  Object? fromDatabase(Object? value, TypeInfo<Object?> type) {
    if (value == null) {
      return null;
    }
    final wanted = type.type;
    if (wanted == DateTime) {
      return switch (value) {
        DateTime() => value.isUtc ? value : _utc(value),
        String() => _utc(DateTime.parse(value)),
        int() => DateTime.fromMillisecondsSinceEpoch(value, isUtc: true),
        _ => value,
      };
    }
    if (wanted == bool) {
      return switch (value) {
        int() => value != 0,
        String() => value == '1' || value.toLowerCase().startsWith('t'),
        _ => value,
      };
    }
    if (wanted == int) {
      return switch (value) {
        String() => int.tryParse(value) ?? value,
        BigInt() => value.toInt(),
        double() when value == value.truncateToDouble() => value.toInt(),
        _ => value,
      };
    }
    if (wanted == BigInt) {
      return switch (value) {
        String() =>
          BigInt.tryParse(value.replaceFirst(_zeroFraction, '')) ?? value,
        int() => BigInt.from(value),
        _ => value,
      };
    }
    if (wanted == double || wanted == num) {
      return switch (value) {
        int() when wanted == double => value.toDouble(),
        String() => num.tryParse(value)?.toDouble() ?? value,
        _ => value,
      };
    }
    if (wanted == Uint8List || type is ListType<int>) {
      return value is List<int> && value is! Uint8List
          ? Uint8List.fromList(value)
          : value;
    }
    if (type is ListType<Object?> && value is List<Object?>) {
      // An array column: each element as a single value of its type.
      return [
        for (final element in value) fromDatabase(element, type.element),
      ];
    }
    if (wanted == String && value is! String && value is! Uint8List) {
      return '$value';
    }
    return value;
  }

  static final _zeroFraction = RegExp(r'\.0+$');

  static DateTime _utc(DateTime parsed) => DateTime.utc(
    parsed.year,
    parsed.month,
    parsed.day,
    parsed.hour,
    parsed.minute,
    parsed.second,
    parsed.millisecond,
    parsed.microsecond,
  );

  // --------------------------------------------------------------- errors

  @override
  DataAccessException translate(SqlError error, {String? sql}) {
    final statement = sql ?? error.sql;
    final state = error.sqlState;
    final message = error.message;
    if (state == null) {
      return unknown(error, sql: statement);
    }
    switch (state) {
      case '23505':
        return DuplicateKeyException(
          message,
          cause: error,
          sql: statement,
          constraint: error.constraint,
        );
      case '40001':
        return CannotSerializeTransactionException(
          message,
          cause: error,
          sql: statement,
        );
      case '40P01':
        return DeadlockLoserDataAccessException(
          message,
          cause: error,
          sql: statement,
        );
      case '55P03':
        return CannotAcquireLockException(
          message,
          cause: error,
          sql: statement,
        );
      case '57014':
        return QueryTimeoutException(message, cause: error, sql: statement);
      case '25006':
        return InvalidDataAccessResourceUsageException(
          message,
          cause: error,
          sql: statement,
        );
      case '42501':
        // insufficient_privilege: a missing grant, or a row-level security
        // policy that refuses the write.
        return PermissionDeniedDataAccessException(
          message,
          cause: error,
          sql: statement,
        );
    }
    if (state.startsWith('23')) {
      return DataIntegrityViolationException(
        message,
        cause: error,
        sql: statement,
        constraint: error.constraint,
      );
    }
    if (state == '22025') {
      // A `like` pattern that ends with its escape character: the caller's
      // pattern is wrong (a derived query escapes its text itself).
      return InvalidDataArgumentException(
        r'A LIKE pattern must not end with the escape character \: '
        r'write \\ for a backslash',
        cause: error,
        sql: statement,
      );
    }
    if (state == '22021') {
      return InvalidDataArgumentException(
        'A text value contains a character the database encoding cannot '
        'hold (a NUL, U+0000, or invalid UTF-8)',
        cause: error,
        sql: statement,
      );
    }
    if (state.startsWith('22')) {
      return DataIntegrityViolationException(
        message,
        cause: error,
        sql: statement,
      );
    }
    if (_grammar.contains(state)) {
      return BadSqlGrammarException(message, cause: error, sql: statement);
    }
    if (state.startsWith('42')) {
      return InvalidDataAccessResourceUsageException(
        message,
        cause: error,
        sql: statement,
      );
    }
    // Connection, authentication, shutdown, resources, missing database.
    if (state.startsWith('08') ||
        state.startsWith('28') ||
        state.startsWith('53') ||
        state.startsWith('57') ||
        state == '3D000') {
      return DataAccessResourceFailureException(
        message,
        cause: error,
        sql: statement,
      );
    }
    return unknown(error, sql: statement);
  }

  // Syntax errors and names that do not exist.
  static const _grammar = {
    '42000',
    '42601',
    '42602',
    '42622',
    '42701',
    '42702',
    '42703',
    '42704',
    '42883',
    '42804',
    '42P01',
    '42P02',
    '42P10',
    '42P18',
  };
}

// What a property type asks of its column.
enum _Kind {
  integer,
  real,
  text,
  boolean,
  timestamp,
  bytes,
  big;

  static _Kind? of(TypeInfo<Object?> type) {
    if (type is EnumType) {
      return text;
    }
    if (type is ListType<int>) {
      return bytes;
    }
    final dart = type.type;
    if (dart == int) {
      return integer;
    }
    if (dart == double || dart == num) {
      return real;
    }
    if (dart == String) {
      return text;
    }
    if (dart == bool) {
      return boolean;
    }
    if (dart == DateTime) {
      return timestamp;
    }
    if (dart == Uint8List) {
      return bytes;
    }
    if (dart == BigInt) {
      return big;
    }
    return null;
  }
}

// JSON in PostgreSQL: a `jsonb` or `json` column.
final class _PostgresJsonStorage extends JsonStorage {
  const _PostgresJsonStorage(this.columnType);

  @override
  final String columnType;

  // `jsonb` for a binary property and `json` for a textual one, exactly:
  // the two compare and index differently.
  @override
  bool fits(String declared) =>
      declared.toLowerCase() == columnType.toLowerCase();

  // The JSON is sent as text, which the server takes as JSON only through
  // a cast.
  @override
  String get marker => 'CAST(? AS $columnType)';

  // The driver decodes `json` and `jsonb` (a JSON string comes as its
  // text, which is not to be decoded again); a text that is no value of
  // the property's type is read by the converter.
  @override
  Object? fromDatabase(Object value) => value;
}
