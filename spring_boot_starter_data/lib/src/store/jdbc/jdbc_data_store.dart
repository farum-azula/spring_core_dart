/// A [DataStore] that keeps the aggregates in the tables of a SQL
/// database, through a [DataSource].
///
/// Every statement is written by the [SqlGenerator] (quoted names, bound
/// values) and run by a `JdbcTemplate` on a connection the transaction
/// aware `DataSourceUtils` gives: the connection of the running
/// transaction of the data source (a `@Transactional` service, a
/// `TransactionTemplate`, the repository's own write transaction) or, with
/// none, one of the pool for that statement. A write that needs several
/// statements (a root and its children) runs in a transaction of its own
/// when the caller has none, so it is all or nothing. Errors are the
/// dialect's translation of the driver's (`DuplicateKeyException`,
/// `CannotAcquireLockException`...), with the SQL; statements are logged
/// by the template (`spring.jdbc.core.JdbcTemplate` at debug, the values
/// at trace, masked).
///
/// Derived queries reach it as a `Criteria` (the build parses the method's
/// name into a `PartTree`, as Spring's `PartTreeJdbcQuery` does) and
/// `@Query` methods run on its [named] template (`StringBasedJdbcQuery`).
///
/// It behaves as the in-memory store does, which is the reference:
///
/// - **Ids.** A null `int` id is generated by the database (the
///   dialect's identity column) and read back; any other id is inserted as
///   it is. A duplicate is a `DuplicateKeyException`.
/// - **Versions.** An insert sets the version to 1 (or the time); an update
///   is `update ... where id = ? and version = ?` with the version raised;
///   no row matched is an `OptimisticLockingFailureException` for a
///   versioned entity and an `IncorrectUpdateSemanticsDataAccessException`
///   for one without a version. A delete with a version checks it too.
/// - **Children** of a `@MappedCollection` are rows of their own table with
///   the id of the root (`<root table>_id` or the annotation's `idColumn`)
///   and, for a list or a map, the position or key (`<root table>_key` or
///   `keyColumn`). They are deleted and inserted again on every save, in
///   the same transaction, and loaded for all the roots of a read at once
///   (one select for each collection, never one for each root). One level
///   of children is supported: a child with a collection of its own is
///   refused with a clear message.
/// - **Locks.** A read with a lock appends the dialect's lock clause
///   (`FOR UPDATE`, `FOR SHARE`, `NOWAIT`, `SKIP LOCKED`) and sets the
///   timeout statement where the dialect has one; a database that locks as
///   a whole (SQLite) takes its write lock before the query, so the query
///   must be the first statement of its transaction, and `skipLocked` and
///   the timeout are moot there (another writer simply waits, or fails with
///   the busy timeout of the connection). A locking read outside a
///   transaction is an `IllegalTransactionStateException`: it never runs
///   unlocked.
/// - **Deletes** remove the children first, then the root (Spring's order,
///   so a schema without `ON DELETE CASCADE` works).
///
/// - **Functions** ([callFunction], the `@Procedure` methods): with a dialect
///   that has them (PostgreSQL) the store calls a function by name with
///   named arguments, `select * from "name"("argument" => ?)`, on the
///   connection of the running transaction; the capability is false for
///   the other dialects (SQLite), and a call is refused.
///
/// What a database cannot match is documented here and tested: the order of
/// strings is the database's collation (SQLite's binary order equals the
/// in-memory one; PostgreSQL's depends on its collation); equal sort keys
/// are ordered by id, not by insertion. (`ignoreCase` folds every letter
/// on both: SQLite's driver registers a `lower` of its own.)
///
/// Spring (Java):
/// `org.springframework.data.jdbc.core.JdbcAggregateTemplate` (over
/// `DefaultDataAccessStrategy`).
final class JdbcDataStore
    implements
        TransactionalDataStore,
        FunctionDataStore,
        RowReadingDataStore,
        EntityCheckingDataStore {
  /// A store over [dataSource], converting with [converter]; table and
  /// column names of children come from [namingStrategy] (the one of the
  /// mapping context). [logSettings] and [queryTimeout] go to the
  /// statements' template.
  JdbcDataStore({
    required this.dataSource,
    required this.converter,
    this.namingStrategy = const NamingStrategy(),
    this.name = 'jdbc',
    JdbcLogSettings logSettings = const JdbcLogSettings(),
    Duration? queryTimeout,
  }) : jdbc = JdbcTemplate(
         dataSource,
         queryTimeout: queryTimeout,
         logSettings: logSettings,
         introspector: converter.introspector,
       ),
       sql = SqlGenerator(dialect: dataSource.dialect, converter: converter),
       transactionManager = DataSourceTransactionManager(dataSource) {
    named = NamedParameterJdbcTemplate(jdbc);
  }

  /// The database the aggregates are in.
  final DataSource dataSource;

  /// Turns instances into rows and back.
  final EntityConverter converter;

  /// Names the tables and columns of children.
  final NamingStrategy namingStrategy;

  @override
  final String name;

  /// Runs the store's statements: logs them, translates their errors, uses
  /// the connection of the running transaction.
  final JdbcTemplate jdbc;

  /// [jdbc] with `:name` parameters, for the `@Query` methods.
  late final NamedParameterJdbcTemplate named;

  /// Writes the SQL.
  final SqlGenerator sql;

  /// The transaction manager of [dataSource] the repositories of this
  /// store run their writes in: a transaction of a service on the same
  /// data source is the one they join.
  @override
  final DataSourceTransactionManager transactionManager;

  /// Transactions, locks and the SQL of `@Query`; database functions when
  /// the dialect has them (PostgreSQL).
  @override
  DataStoreCapabilities get capabilities => DataStoreCapabilities(
    transactions: true,
    locks: true,
    queries: true,
    functions: dialect.supportsFunctions,
  );

  /// The collection properties (`Map`, `List`, `Set`) without `@Json`
  /// that the database has no column for: problems of the repository of
  /// [entity], found when it is created.
  @override
  List<String> mappingProblems(PersistentEntity<Object> entity) =>
      CollectionColumns(dialect).problemsOf(entity);

  /// The dialect: it reads the values of the rows.
  @override
  ColumnValueReader get valueReader => dialect;

  /// The database's dialect.
  SqlDialect get dialect => dataSource.dialect;

  /// How many ids go in one `in (...)` (below SQLite's limit of bound
  /// values).
  static const _chunk = 500;

  // ------------------------------------------------------------- plumbing

  // Runs a write: in the running transaction of the data source (which must
  // not be read only) or, with none, in one of its own that commits when
  // the write is done.
  Future<R> _write<R>(String operation, Future<R> Function() body) {
    final holder = DataSourceUtils.currentHolder(dataSource);
    if (holder != null) {
      if (holder.readOnly) {
        throw InvalidDataAccessResourceUsageException(
          'cannot execute $operation in a read-only transaction',
        );
      }
      return body();
    }
    return runInTransaction<R>(
      transactionManager,
      TransactionDefinition(name: '$name.$operation'),
      (_) => body(),
    );
  }

  // The statements a read with a lock needs before its select.
  Future<void> _prepareLock(LockMode? lock, Duration? timeout) async {
    if (lock == null) {
      return;
    }
    if (DataSourceUtils.currentHolder(dataSource) == null) {
      throw IllegalTransactionStateException(
        'A read with ${lock.name} needs a transaction: it never runs '
        'without its lock',
      );
    }
    switch (dialect.lockStrategy) {
      case LockStrategy.databaseLock:
        await DataSourceUtils.requireWriteLock(dataSource);
      case LockStrategy.rowLocks:
        if (timeout != null && timeout > Duration.zero) {
          if (dialect.lockTimeoutStatement(timeout) case final statement?) {
            await jdbc.execute(statement);
          }
        }
    }
  }

  String _lockClause(
    LockMode? lock,
    Duration? timeout,
    bool skipLocked,
  ) => lock == null
      ? ''
      : dialect.lockClause(lock, timeout: timeout, skipLocked: skipLocked);

  PersistentProperty _requireId(PersistentEntity<Object> entity) =>
      entity.idProperty ??
      (throw InvalidDataAccessApiUsageException(
        '${entity.introspection.className} has no @Id property: the JDBC '
        'store keeps aggregates by id',
      ));

  String _where(PersistentEntity<Object> entity, PersistentProperty p) =>
      '${entity.introspection.className}.${p.name}';

  // ------------------------------------------------------------- children

  final _childTables =
      Map<PersistentEntity<Object>, List<_ChildTable>>.identity();

  List<_ChildTable> _children(PersistentEntity<Object> entity) =>
      _childTables.putIfAbsent(entity, () {
        final tables = <_ChildTable>[];
        for (final property in entity.properties) {
          if (!property.isMappedCollection) {
            continue;
          }
          final child = property.childEntity!;
          if (child.properties.any((p) => p.isMappedCollection)) {
            throw InvalidDataAccessApiUsageException(
              '${_where(entity, property)}: the children '
              '${child.introspection.className} have a collection of '
              'their own; the JDBC store supports one level of children',
            );
          }
          final isMap = property.type is MapType<Object?, Object?>;
          final isList = property.type is ListType<Object?>;
          tables.add(
            _ChildTable(
              property: property,
              entity: child,
              reverseColumn: namingStrategy.reverseColumnName(
                entity.tableName,
                property.mappedCollection,
              ),
              keyColumn: isMap || isList
                  ? namingStrategy.keyColumnName(
                      entity.tableName,
                      property.mappedCollection,
                    )
                  : null,
              isMap: isMap,
            ),
          );
        }
        return tables;
      });

  Future<void> _insertChildren(
    PersistentEntity<Object> entity,
    Object instance,
    Object? rootId,
  ) async {
    final tables = _children(entity);
    if (tables.isEmpty) {
      return;
    }
    for (final table in tables) {
      final value = table.property.getValue(instance);
      if (value == null) {
        continue;
      }
      final elements = switch (value) {
        final Map<Object?, Object?> map => [
          for (final entry in map.entries)
            (converter.toColumnValue(entry.key), entry.value),
        ],
        final List<Object?> list => [
          for (final (index, element) in list.indexed) (index, element),
        ],
        final Iterable<Object?> items => [
          for (final element in items) (null, element),
        ],
        _ => throw MappingException(
          '${_where(entity, table.property)}: a mapped collection must be '
          'a List, a Set or a Map, not a ${value.runtimeType}',
        ),
      };
      final childId = table.entity.idProperty;
      for (final (key, element) in elements) {
        final row = converter.write(table.entity, element!);
        if (childId != null &&
            row[childId.columnName] == null &&
            childId.type.type == int) {
          row.remove(childId.columnName);
        }
        row[table.reverseColumn] = rootId;
        if (table.keyColumn != null) {
          row[table.keyColumn!] = key;
        }
        final statement = sql.insert(table.entity, row);
        await jdbc.update(statement.sql, statement.parameters);
      }
    }
  }

  Future<void> _deleteChildren(
    PersistentEntity<Object> entity,
    Object? rootId,
  ) async {
    for (final table in _children(entity)) {
      final statement = sql.deleteChildren(
        table.entity,
        table.reverseColumn,
        rootId,
      );
      await jdbc.update(statement.sql, statement.parameters);
    }
  }

  // ---------------------------------------------------------------- write

  @override
  Future<T> insert<T extends Object>(PersistentEntity<T> entity, T instance) =>
      _write('insert', () async {
        final idProperty = _requireId(entity);
        final versionProperty = entity.versionProperty;
        var id = converter.toColumnValue(idProperty.getValue(instance));
        final generated = id == null;
        if (generated && idProperty.type.type != int) {
          throw InvalidDataAccessApiUsageException(
            'The id ${_where(entity, idProperty)} is null and a '
            '${idProperty.type.type} cannot be generated: set it before '
            'saving',
          );
        }
        final version = versionProperty == null
            ? null
            : _nextVersion(versionProperty, null);
        final row = converter.write(entity, instance);
        if (generated) {
          row.remove(idProperty.columnName);
        }
        if (versionProperty != null) {
          row[versionProperty.columnName] = converter.toColumnValue(version);
        }
        final statement = sql.insert(entity, row);
        if (generated) {
          final holder = KeyHolder();
          await jdbc.updateWithKeyHolder(
            statement.sql,
            statement.parameters,
            holder,
            keyColumn: idProperty.columnName,
          );
          id = switch (holder.key) {
            final int key => key,
            final BigInt key => key.toInt(),
            final String key when int.tryParse(key) != null => int.parse(key),
            _ => throw DataAccessResourceFailureException(
              'The database returned no generated id for the insert into '
              '${entity.tableName}',
              sql: statement.sql,
            ),
          };
        } else {
          await jdbc.update(statement.sql, statement.parameters);
        }
        await _insertChildren(entity, instance, id);
        return await _withIdAndVersion(
          entity,
          instance,
          idProperty,
          generated ? id : null,
          versionProperty,
          version,
        );
      });

  @override
  Future<T> update<T extends Object>(
    PersistentEntity<T> entity,
    T instance, {
    Object? expectedVersion,
  }) => _write('update', () async {
    final idProperty = _requireId(entity);
    final versionProperty = entity.versionProperty;
    final id = converter.toColumnValue(idProperty.getValue(instance));
    if (id == null) {
      throw InvalidDataAccessApiUsageException(
        'Cannot update ${entity.introspection.className}: its id is null',
      );
    }
    final expected = versionProperty == null
        ? null
        : converter.toColumnValue(
            expectedVersion ?? versionProperty.getValue(instance),
          );
    final version = versionProperty == null
        ? null
        : _nextVersion(versionProperty, expected);
    final row = converter.write(entity, instance);
    if (versionProperty != null) {
      row[versionProperty.columnName] = converter.toColumnValue(version);
    }
    final statement = sql.update(
      entity,
      row,
      id: id,
      expectedVersion: expected,
    );
    final changed = await jdbc.update(statement.sql, statement.parameters);
    if (changed == 0) {
      throw versionProperty == null
          ? IncorrectUpdateSemanticsDataAccessException(
              'Failed to update ${entity.introspection.className} in table '
              '${entity.tableName}: no row has this id (an entity with an '
              'id is updated, not inserted; give an entity whose id is set '
              'by the application a @Version property)',
            )
          : OptimisticLockingFailureException(
              'Failed to update ${entity.introspection.className} in table '
              '${entity.tableName}: it was changed or deleted since it was '
              'loaded (its version no longer matches)',
            );
    }
    await _deleteChildren(entity, id);
    await _insertChildren(entity, instance, id);
    return await _withIdAndVersion(
      entity,
      instance,
      idProperty,
      null,
      versionProperty,
      version,
    );
  });

  @override
  Future<bool> deleteById<T extends Object>(
    PersistentEntity<T> entity,
    Object id, {
    Object? expectedVersion,
  }) => _write('delete', () async {
    final columnId = converter.toColumnValue(id);
    final versionProperty = entity.versionProperty;
    final checked = expectedVersion != null && versionProperty != null;
    await _deleteChildren(entity, columnId);
    final statement = sql.deleteById(
      entity,
      columnId,
      expectedVersion: checked
          ? converter.toColumnValue(expectedVersion)
          : null,
    );
    final changed = await jdbc.update(statement.sql, statement.parameters);
    if (checked && changed == 0) {
      throw OptimisticLockingFailureException(
        'Failed to delete ${entity.introspection.className} from table '
        '${entity.tableName}: it was changed or deleted since it was '
        'loaded (its version no longer matches)',
      );
    }
    return changed > 0;
  });

  @override
  Future<int> deleteWhere<T extends Object>(
    PersistentEntity<T> entity, {
    Criteria? criteria,
  }) => _write('delete', () async {
    for (final table in _children(entity)) {
      final statement = sql.deleteChildrenWhere(
        table.entity,
        table.reverseColumn,
        entity,
        criteria,
      );
      await jdbc.update(statement.sql, statement.parameters);
    }
    final statement = sql.deleteWhere(entity, criteria);
    return await jdbc.update(statement.sql, statement.parameters);
  });

  @override
  Future<List<T>> deleteWhereAndReturn<T extends Object>(
    PersistentEntity<T> entity, {
    Criteria? criteria,
  }) => _write('delete', () async {
    final found = await find(entity, criteria: criteria);
    if (found.isEmpty) {
      return found;
    }
    final ids = [
      for (final instance in found)
        converter.toColumnValue(_requireId(entity).getValue(instance)),
    ];
    for (final chunk in _chunks(ids)) {
      for (final table in _children(entity)) {
        await jdbc.update(
          'delete from ${sql.table(table.entity)} where '
          '${dialect.quote(table.reverseColumn)} in '
          '(${List.filled(chunk.length, '?').join(', ')})',
          chunk,
        );
      }
      await jdbc.update(
        'delete from ${sql.table(entity)} where '
        '${dialect.quote(_requireId(entity).columnName)} in '
        '(${List.filled(chunk.length, '?').join(', ')})',
        chunk,
      );
    }
    return found;
  });

  // ----------------------------------------------------------------- read

  @override
  Future<T?> findById<T extends Object>(
    PersistentEntity<T> entity,
    Object id, {
    LockMode? lock,
    Duration? lockTimeout,
    bool skipLocked = false,
  }) async {
    await _prepareLock(lock, lockTimeout);
    final statement = sql.selectById(
      entity,
      converter.toColumnValue(id),
      lock: _lockClause(lock, lockTimeout, skipLocked),
    );
    final rows = await jdbc.query<JdbcRow>(
      statement.sql,
      statement.parameters,
      (row) => row,
    );
    return (await readAggregates<T>(entity, rows)).firstOrNull;
  }

  @override
  Future<List<T>> findAllById<T extends Object>(
    PersistentEntity<T> entity,
    Iterable<Object> ids,
  ) async {
    final wanted = {for (final id in ids) converter.toColumnValue(id)}.toList();
    final rows = <JdbcRow>[];
    for (final chunk in _chunks(wanted)) {
      final statement = sql.selectByIds(entity, chunk);
      rows.addAll(
        await jdbc.query<JdbcRow>(
          statement.sql,
          statement.parameters,
          (row) => row,
        ),
      );
    }
    if (wanted.length > _chunk) {
      // Chunks come back in turn: restore the order of the table.
      final idColumn = _requireId(entity).columnName;
      rows.sort((a, b) => _compareRaw(a[idColumn], b[idColumn]));
    }
    return await readAggregates<T>(entity, rows);
  }

  @override
  Future<List<T>> find<T extends Object>(
    PersistentEntity<T> entity, {
    Criteria? criteria,
    Sort sort = Sort.unsorted,
    int? offset,
    int? limit,
    bool distinct = false,
    LockMode? lock,
    Duration? lockTimeout,
    bool skipLocked = false,
  }) async {
    await _prepareLock(lock, lockTimeout);
    final statement = sql.select(
      entity,
      criteria: criteria,
      sort: sort,
      offset: offset,
      limit: limit,
      distinct: distinct,
      lock: _lockClause(lock, lockTimeout, skipLocked),
    );
    final rows = await jdbc.query<JdbcRow>(
      statement.sql,
      statement.parameters,
      (row) => row,
    );
    return await readAggregates<T>(entity, rows);
  }

  @override
  Future<int> count<T extends Object>(
    PersistentEntity<T> entity, {
    Criteria? criteria,
  }) {
    final statement = sql.count(entity, criteria);
    return jdbc.queryForObject<int>(statement.sql, statement.parameters);
  }

  @override
  Future<bool> exists<T extends Object>(
    PersistentEntity<T> entity, {
    Criteria? criteria,
  }) async {
    final statement = sql.exists(entity, criteria);
    final rows = await jdbc.query<int>(
      statement.sql,
      statement.parameters,
      (row) => 1,
    );
    return rows.isNotEmpty;
  }

  // ------------------------------------------------------------ functions

  /// Calls the database function [name] with [arguments] by name, as the
  /// dialect writes the call (`select * from "name"("argument" => ?)`),
  /// through the store's template: on the connection of the running
  /// transaction, logged, its errors translated. A list is bound as one
  /// array argument (it is not expanded as for `in (:ids)`).
  ///
  /// Throws an `InvalidDataAccessResourceUsageException` when the dialect
  /// has no functions (see [capabilities]).
  @override
  Future<List<Map<String, Object?>>> callFunction(
    String name,
    Map<String, Object?> arguments,
  ) {
    if (!dialect.supportsFunctions) {
      return Future.error(
        InvalidDataAccessResourceUsageException(
          'Cannot call the function $name: ${dialect.name} has no '
          'functions to call by name',
        ),
        StackTrace.current,
      );
    }
    final names = arguments.keys.toList();
    return jdbc.queryForMaps(
      dialect.functionCall(name, names),
      BoundParameters(arguments.values.toList(), names),
    );
  }

  // -------------------------------------------------------------- reading

  /// The aggregates of [entity] that [rows] hold (rows of a query that
  /// returns the columns of its table), with their children: each
  /// collection of children is read for all the roots in one select.
  ///
  /// A `@Query` that returns an entity uses it too: the children are not
  /// in its result, so they are loaded here and the aggregate is whole
  /// (Spring Data JDBC maps only what the query returns). The query must
  /// return the id when the entity has children.
  @override
  Future<List<T>> readAggregates<T extends Object>(
    PersistentEntity<T> entity,
    List<JdbcRow> rows,
  ) async {
    if (rows.isEmpty) {
      return const [];
    }
    final tables = _children(entity);
    final childrenOf = <Object?, Map<String, Object?>>{};
    if (tables.isNotEmpty) {
      final idColumn = _requireId(entity).columnName;
      if (!rows.first.has(idColumn)) {
        throw MappingException(
          'The rows have no column $idColumn (the id of '
          '${entity.introspection.className}), and its children cannot be '
          'loaded without it (columns: ${rows.first.columns.join(', ')})',
        );
      }
      final ids = [
        for (final row in rows)
          if (row[idColumn] != null) row[idColumn],
      ];
      for (final table in tables) {
        final byRoot = await _loadChildren(table, ids);
        for (final MapEntry(:key, :value) in byRoot.entries) {
          (childrenOf[key] ??= {})[table.property.name] = value;
        }
      }
    }
    final idColumn = entity.idProperty?.columnName;
    return [
      for (final row in rows)
        converter.read<T>(
          entity,
          _values(entity, row),
          children: idColumn != null && row.has(idColumn)
              ? childrenOf[row[idColumn]] ?? const {}
              : const {},
        ),
    ];
  }

  // The values of the columns of [entity] that [row] has, as the dialect
  // reads them.
  Map<String, Object?> _values(PersistentEntity<Object> entity, JdbcRow row) {
    final values = <String, Object?>{};
    for (final property in entity.columns) {
      if (row.has(property.columnName)) {
        final value = row[property.columnName];
        values[property.columnName] = value == null
            ? null
            : property.json == null
            ? dialect.fromDatabase(value, property.type)
            : _json(entity, property, value);
      }
    }
    return values;
  }

  // The decoded JSON of what the column of a `@Json` property gave, as
  // the dialect reads it.
  Object? _json(
    PersistentEntity<Object> entity,
    PersistentProperty property,
    Object value,
  ) {
    try {
      return dialect.jsonStorage(property.json!).fromDatabase(value);
    } on FormatException {
      throw MappingException(
        '${_where(entity, property)}: the stored value is not JSON',
      );
    }
  }

  // The children of the roots [rootIds] of a collection, by root id (as the
  // database holds it): a list in the order of its positions, a map by
  // key.
  Future<Map<Object?, Object>> _loadChildren(
    _ChildTable table,
    List<Object?> rootIds,
  ) async {
    final byRoot = <Object?, List<(Object?, Object)>>{};
    for (final chunk in _chunks(rootIds.toSet().toList())) {
      final statement = sql.selectChildren(
        table.entity,
        table.reverseColumn,
        table.keyColumn,
        chunk,
      );
      final rows = await jdbc.query<JdbcRow>(
        statement.sql,
        statement.parameters,
        (row) => row,
      );
      final keyType = table.isMap
          ? (table.property.type as MapType<Object?, Object?>).key
          : null;
      for (final row in rows) {
        final child = converter.read<Object>(
          table.entity,
          _values(table.entity, row),
        );
        final rawKey = table.keyColumn == null ? null : row[table.keyColumn!];
        final key = keyType == null || rawKey == null
            ? rawKey
            : converter.fromColumnValue(
                dialect.fromDatabase(rawKey, keyType),
                keyType,
                where: '${_where(table.entity, table.property)} key',
              );
        (byRoot[row[table.reverseColumn]] ??= []).add((key, child));
      }
    }
    return {
      for (final MapEntry(:key, :value) in byRoot.entries)
        key: table.isMap
            ? {for (final (k, child) in value) k: child}
            : [for (final (_, child) in value) child],
    };
  }

  // ------------------------------------------------------------- internals

  Iterable<List<Object?>> _chunks(List<Object?> values) sync* {
    for (var i = 0; i < values.length; i += _chunk) {
      yield values.sublist(
        i,
        i + _chunk > values.length ? values.length : i + _chunk,
      );
    }
  }

  static int _compareRaw(Object? a, Object? b) {
    if (a is num && b is num) {
      return a.compareTo(b);
    }
    if (a is String && b is String) {
      return a.compareTo(b);
    }
    return 0;
  }

  Object _nextVersion(PersistentProperty property, Object? old) {
    if (property.type.type == DateTime) {
      var now = DateTime.now();
      if (old is DateTime && !now.isAfter(old)) {
        now = old.add(const Duration(microseconds: 1));
      }
      return now;
    }
    return (old is int ? old : 0) + 1;
  }

  // The instance as saved: with the generated id and the new version. A
  // failed write leaves the application's instance untouched, as the
  // changes are applied last.
  T _withIdAndVersion<T extends Object>(
    PersistentEntity<T> entity,
    T instance,
    PersistentProperty idProperty,
    Object? generatedId,
    PersistentProperty? versionProperty,
    Object? version,
  ) {
    final changes = <String, Object?>{
      idProperty.name: ?generatedId,
      if (versionProperty != null) versionProperty.name: version,
    };
    return changes.isEmpty
        ? instance
        : converter.withValues(entity, instance, changes);
  }

  @override
  String toString() => 'JdbcDataStore($name, ${dataSource.name})';
}

// The table of one @MappedCollection: its children's entity and the
// columns that tie a child to its root and to its place.
final class _ChildTable {
  const _ChildTable({
    required this.property,
    required this.entity,
    required this.reverseColumn,
    required this.keyColumn,
    required this.isMap,
  });

  final PersistentProperty property;
  final PersistentEntity<Object> entity;
  final String reverseColumn;
  final String? keyColumn;
  final bool isMap;
}
