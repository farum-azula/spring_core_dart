      expect(await scalar(connection, 'SELECT count(*) FROM items'), 2);
    });
  });

  group('streams', () {
    late JdbcConnection connection;

    setUp(() async => connection = await serverConnection());

    test('give every row', () async {
      final rows = await connection.queryStream(
        'SELECT g FROM generate_series(1, ?::int) g',
        [1000],
      ).toList();
      expect(rows, hasLength(1000));
      expect(rows.last['g'], 1000);
    });

    test('cancelling ends the query and frees the connection', () async {
      final first = await connection
          .queryStream('SELECT g FROM generate_series(1, 1000000) g')
          .take(5)
          .map((row) => row['g'])
          .toList();
      expect(first, [1, 2, 3, 4, 5]);
      expect(await scalar(connection, 'SELECT 42'), 42);
    });

    test('an error in the query reaches the stream', () async {
      await expectLater(
        connection.queryStream('SELECT * FROM no_such_table').toList(),
        throwsA(isA<SqlError>().having((e) => e.sqlState, 'state', '42P01')),
      );
      expect(await scalar(connection, 'SELECT 1'), 1);
    });

    test('statements asked meanwhile wait for the stream', () async {
      final order = <String>[];
      final rows = StreamIterator(
        connection.queryStream('SELECT g FROM generate_series(1, 3) g'),
      );
      await rows.moveNext();
      order.add('row ${rows.current['g']}');
      final query = connection
          .query('SELECT 1')
          .then((_) => order.add('query'));
      while (await rows.moveNext()) {
        order.add('row ${rows.current['g']}');
      }
      await query;
      expect(order, ['row 1', 'row 2', 'row 3', 'query']);
    });
  });

  group('transactions', () {
    late JdbcConnection connection;
    late JdbcConnection other;
    late String schema;

    setUp(() async {
      schema = await newSchema();
      connection = await serverConnection(query: 'currentSchema=$schema');
      other = await serverConnection(query: 'currentSchema=$schema');
      await connection.execute(
        'CREATE TABLE counters (id INT PRIMARY KEY, n INT NOT NULL)',
      );
      await connection.execute('INSERT INTO counters VALUES (1, 0), (2, 0)');
    });

    Future<Object?> n(JdbcConnection c, [int id = 1]) =>
        scalar(c, 'SELECT n FROM counters WHERE id = ?', [id]);

    test('commit and rollback', () async {
      await connection.begin();
      await connection.update('UPDATE counters SET n = 5 WHERE id = 1');
      expect(await n(other), 0);
      await connection.commit();
      expect(await n(other), 5);
      await connection.begin();
      await connection.update('UPDATE counters SET n = 9 WHERE id = 1');
      await connection.rollback();
      expect(await n(other), 5);
    });

    test('DDL is transactional', () async {
      await connection.begin();
      await connection.execute('CREATE TABLE gone (a INT)');
      await connection.rollback();
      expect(
        await scalar(connection, "SELECT to_regclass('gone')::text"),
        isNull,
      );
    });

    test("isolation levels are the server's", () async {
      Future<Object?> level(Isolation isolation) async {
        await connection.begin(isolation: isolation);
        try {
          return await scalar(connection, 'SHOW transaction_isolation');
        } finally {
          await connection.rollback();
        }
      }

      expect(await level(Isolation.defaultLevel), 'read committed');
      expect(await level(Isolation.readCommitted), 'read committed');
      // Accepted, and the server runs it as read committed.
      expect(await level(Isolation.readUncommitted), 'read uncommitted');
      expect(await level(Isolation.repeatableRead), 'repeatable read');
      expect(await level(Isolation.serializable), 'serializable');
    });

    test(
      'read committed sees what others commit, repeatable read does not',
      () async {
        await connection.begin(isolation: Isolation.readCommitted);
        expect(await n(connection), 0);
        await other.update('UPDATE counters SET n = 1 WHERE id = 1');
        expect(await n(connection), 1);
        await connection.rollback();

        await connection.begin(isolation: Isolation.repeatableRead);
        expect(await n(connection), 1);
        await other.update('UPDATE counters SET n = 2 WHERE id = 1');
        expect(await n(connection), 1);
        await connection.rollback();
      },
    );

    test('a read only transaction refuses writes', () async {
      await connection.begin(readOnly: true);
      final error = await translated(
        () => connection.update('UPDATE counters SET n = 1'),
      );
      expect(error, isA<InvalidDataAccessResourceUsageException>());
      await connection.rollback();
      expect(await n(connection), 0);
    });

    test(
      'savepoints roll back part of a transaction, also after an error',
      () async {
        await connection.begin();
        await connection.update('UPDATE counters SET n = 1 WHERE id = 1');
        await connection.savepoint('sp');
        await connection.update('UPDATE counters SET n = 2 WHERE id = 1');
        await connection.rollbackToSavepoint('sp');
        expect(await n(connection), 1);
        await connection.savepoint('sp2');
        await expectLater(
          connection.update('UPDATE nope SET n = 1'),
          throwsA(isA<SqlError>()),
        );
        // The failed statement left the transaction aborted: a savepoint
        // brings it back.
        await connection.rollbackToSavepoint('sp2');
        await connection.releaseSavepoint('sp2');
        await connection.update('UPDATE counters SET n = 3 WHERE id = 1');
        await connection.commit();
        expect(await n(other), 3);
      },
    );

    test('an error aborts the transaction until it is rolled back', () async {
      await connection.begin();
      await expectLater(
        connection.query('SELECT * FROM nope'),
        throwsA(isA<SqlError>()),
      );
      final error = await sqlError(() => connection.query('SELECT 1'));
      expect(error.sqlState, '25P02');
      await connection.rollback();
      expect(await scalar(connection, 'SELECT 1'), 1);
    });

    test('serializable: a conflict is a serialization failure', () async {
      await connection.begin(isolation: Isolation.serializable);
      await other.begin(isolation: Isolation.serializable);
      // Each reads what the other writes.
      await connection.query('SELECT sum(n) FROM counters');
      await other.query('SELECT sum(n) FROM counters');
      await connection.update('UPDATE counters SET n = 1 WHERE id = 1');
      await other.update('UPDATE counters SET n = 1 WHERE id = 2');
      await connection.commit();
      final error = await translated(other.commit);
      expect(error, isA<CannotSerializeTransactionException>());
      expect(error, isA<PessimisticLockingFailureException>());
      await other.rollback();
    });

    test('repeatable read: updating a row another changed fails', () async {
      await connection.begin(isolation: Isolation.repeatableRead);
      await other.begin(isolation: Isolation.repeatableRead);
      await n(connection);
      await n(other);
      await connection.update('UPDATE counters SET n = 1 WHERE id = 1');
      await connection.commit();
      final error = await translated(
        () => other.update('UPDATE counters SET n = 2 WHERE id = 1'),
      );
      expect(error, isA<CannotSerializeTransactionException>());
      await other.rollback();
    });

    test('a deadlock: one transaction loses', () async {
      await connection.begin();
      await other.begin();
      await connection.update('UPDATE counters SET n = 1 WHERE id = 1');
      await other.update('UPDATE counters SET n = 1 WHERE id = 2');
      // Each now wants the row of the other.
      final first = translated(
        () => connection.update('UPDATE counters SET n = 2 WHERE id = 2'),
      ).then<Object>((e) => e, onError: (Object e) => e);
      await Future<void>.delayed(const Duration(milliseconds: 300));
      final second = translated(
        () => other.update('UPDATE counters SET n = 2 WHERE id = 1'),
      ).then<Object>((e) => e, onError: (Object e) => e);
      final results = await Future.wait([first, second]);
      expect(
        results.whereType<DeadlockLoserDataAccessException>(),
        hasLength(1),
      );
      await connection.rollback();
      await other.rollback();
    });
  });

  group('locks', () {
    late JdbcConnection connection;
    late JdbcConnection other;

    setUp(() async {
      final schema = await newSchema();
      connection = await serverConnection(query: 'currentSchema=$schema');
      other = await serverConnection(query: 'currentSchema=$schema');
      await connection.execute('CREATE TABLE jobs (id INT PRIMARY KEY)');
      await connection.execute('INSERT INTO jobs VALUES (1), (2), (3)');
    });

    String select(String lock) => 'SELECT id FROM jobs ORDER BY id $lock';

    test('FOR UPDATE NOWAIT fails at once', () async {
      await connection.begin();
      await connection.query(
        select(dialect.lockClause(LockMode.pessimisticWrite)),
      );
      await other.begin();
      final error = await translated(
        () => other.query(
          select(
            dialect.lockClause(
              LockMode.pessimisticWrite,
              timeout: Duration.zero,
            ),
          ),
        ),
      );
      expect(error, isA<CannotAcquireLockException>());
      await other.rollback();
      await connection.rollback();
    });

    test('SET LOCAL lock_timeout bounds the wait', () async {
      await connection.begin();
      await connection.query(
        select(dialect.lockClause(LockMode.pessimisticWrite)),
      );
      await other.begin();
      await other.execute(
        dialect.lockTimeoutStatement(const Duration(milliseconds: 200))!,
      );
      final watch = Stopwatch()..start();
      final error = await translated(
        () => other.query(
          select(dialect.lockClause(LockMode.pessimisticWrite)),
        ),
      );
      expect(error, isA<CannotAcquireLockException>());
      expect(watch.elapsed, lessThan(const Duration(seconds: 5)));
      await other.rollback();
      await connection.rollback();
    });

    test('SKIP LOCKED leaves out the rows another holds', () async {
      await connection.begin();
      await connection.query(
        'SELECT id FROM jobs WHERE id = 1 '
        '${dialect.lockClause(LockMode.pessimisticWrite)}',
      );
      await other.begin();
      final result = await other.query(
        select(
          dialect.lockClause(LockMode.pessimisticWrite, skipLocked: true),
        ),
      );
      expect(result.rows.map((r) => r['id']), [2, 3]);
      await other.rollback();
      await connection.rollback();
    });

    test(
      'FOR SHARE locks do not block each other, but block a writer',
      () async {
        await connection.begin();
        await other.begin();
        final share = dialect.lockClause(LockMode.pessimisticRead);
        await connection.query(select(share));
        await other.query(select(share));
        final error = await translated(
          () => other.query(
            select(
              dialect.lockClause(
                LockMode.pessimisticWrite,
                timeout: Duration.zero,
              ),
            ),
          ),
        );
        expect(error, isA<CannotAcquireLockException>());
        await other.rollback();
        await connection.rollback();
      },
    );

    test('LIMIT and OFFSET come before the lock clause', () async {
      await connection.begin();
      final result = await connection.query(
        'SELECT id FROM jobs ORDER BY id ${dialect.limitOffset(1, 1)} '
        '${dialect.lockClause(LockMode.pessimisticWrite)}',
      );
      expect(result.rows.map((r) => r['id']), [2]);
      await connection.rollback();
    });
  });

  group('timeouts', () {
    late JdbcConnection connection;

    setUp(() async => connection = await serverConnection());

    test('a statement past its timeout is cancelled and the connection '
        'goes on', () async {
      await connection.setStatementTimeout(const Duration(milliseconds: 200));
