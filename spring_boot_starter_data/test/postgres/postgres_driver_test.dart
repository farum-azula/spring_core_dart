      );
    });

    test('a database that does not exist', () async {
      final url = Uri.parse(postgresUrl!);
      final error = await sqlError(
        () => connectWith(
          ConnectionSettings(url: url.replace(path: '/no_such_database')),
        ),
      );
      expect(error.sqlState, '3D000');
      expect(
        const PostgresDialect().translate(error),
        isA<DataAccessResourceFailureException>(),
      );
    });

    test('TLS: prefer connects without it to a server that has none, '
        'require refuses to', () async {
      // The server of the tests may have TLS or not: both are fine for
      // prefer; require must either connect with TLS or say there is none.
      final prefer = await serverConnection(properties: {'sslmode': 'prefer'});
      expect(await scalar(prefer, 'SELECT 1'), 1);
      final usesTls = await scalar(
        prefer,
        'SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()',
      );
      final require = (await postgresDriver()).connect(
        serverSettings(properties: {'sslmode': 'require'}),
      );
      if (usesTls == true) {
        final connection = await require;
        addTearDown(connection.close);
        expect(await scalar(connection, 'SELECT 1'), 1);
      } else {
        final error = await sqlError(() => require);
        expect(error.message, contains('does not support SSL'));
      }
      final disabled = await serverConnection(
        properties: {'sslmode': 'disable'},
      );
      expect(
        await scalar(
          disabled,
          'SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()',
        ),
        false,
      );
    });
  });

  group('values', () {
    late JdbcConnection connection;

    setUp(() async {
      final schema = await newSchema();
      connection = await serverConnection(query: 'currentSchema=$schema');
      await connection.execute('''
CREATE TABLE types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  n BIGINT, d DOUBLE PRECISION, s TEXT, b BOOLEAN, t TIMESTAMPTZ,
  y BYTEA, big NUMERIC
)''');
    });

    test('round trip', () async {
      final moment = DateTime.utc(2026, 3, 1, 10, 20, 30, 456, 789);
      final bytes = Uint8List.fromList([0, 1, 2, 255]);
      final big = BigInt.parse('123456789012345678901234567890');
      await connection.update(
        'INSERT INTO types (n, d, s, b, t, y, big) '
        'VALUES (?, ?, ?, ?, ?, ?, ?)',
        [
          bigValue,
          1.5,
          'Ünïcode \u{1F600}',
          true,
          dialect.toDatabase(moment),
          bytes,
          dialect.toDatabase(big),
        ],
      );
      final row = (await connection.query('SELECT * FROM types')).rows.single;
      expect(row['n'], bigValue);
      expect(row['d'], 1.5);
      expect(row['s'], 'Ünïcode \u{1F600}');
      expect(row['b'], isTrue);
      expect(row['t'], moment);
      expect((row['t']! as DateTime).isUtc, isTrue);
      expect(row['y'], bytes);
      expect(dialect.fromDatabase(row['big'], const ClassType<BigInt>()), big);
    });

    test('nulls and extreme doubles', () async {
      await connection.update(
        'INSERT INTO types (n, d, s, b, t, y, big) '
        'VALUES (?, ?, ?, ?, ?, ?, ?)',
        const [null, null, null, null, null, null, null],
      );
      await connection.update('INSERT INTO types (d) VALUES (?)', [
        double.infinity,
      ]);
      await connection.update('INSERT INTO types (d) VALUES (?)', [
        double.nan,
      ]);
      final rows = (await connection.query(
        'SELECT * FROM types ORDER BY id',
      )).rows;
      expect(rows[0].values.skip(1), everyElement(isNull));
      expect(rows[1]['d'], double.infinity);
      expect(rows[2]['d'], isNaN);
    });

    test('a local time is stored as the instant it is', () async {
      final local = DateTime(2026, 7, 1, 12);
      await connection.update('INSERT INTO types (t) VALUES (?)', [
        dialect.toDatabase(local),
      ]);
      final read = await scalar(connection, 'SELECT t FROM types');
      expect(read, local.toUtc());
    });

    test('hostile text is a value, never SQL', () async {
      const hostile = "x'); DROP TABLE types; --";
      await connection.update('INSERT INTO types (s) VALUES (?)', [hostile]);
      expect(
        await scalar(connection, 'SELECT s FROM types WHERE s = ?', [hostile]),
        hostile,
      );
      expect(await scalar(connection, 'SELECT count(*) FROM types'), 1);
    });

    test('a ? or a quoted ? in the SQL is not a marker', () async {
      await connection.update('INSERT INTO types (s) VALUES (?)', ['a?b']);
      expect(
        await scalar(
          connection,
          "SELECT s FROM types WHERE s = 'a?b' AND n IS NULL "
          'AND s <> ? -- is it ?\n',
          ['other'],
        ),
        'a?b',
      );
    });

    test('count and sum come back as numbers the dialect can read', () async {
      await connection.update('INSERT INTO types (n) VALUES (?)', [4]);
      await connection.update('INSERT INTO types (n) VALUES (?)', [5]);
      expect(await scalar(connection, 'SELECT count(*) FROM types'), 2);
      // sum(bigint) is numeric, which the package gives as text.
      expect(
        dialect.fromDatabase(
          await scalar(connection, 'SELECT sum(n) FROM types'),
          const ClassType<int>(),
        ),
        9,
      );
    });

    test('column labels come back as the SQL names them', () async {
      final result = await connection.query('SELECT 1 AS "A b", 2 AS c');
      expect(result.columns, ['A b', 'c']);
      expect(result.rows.single['a b'], 1);
    });
  });

  group('changes', () {
    late JdbcConnection connection;

    setUp(() async {
