    test('also inside a transaction, which is then rolled back', () async {
      await connection.begin();
      await connection.setStatementTimeout(const Duration(milliseconds: 200));
      final error = await translated(
        () => connection.query('SELECT pg_sleep(5)'),
      );
      expect(error, isA<QueryTimeoutException>());
      await connection.setStatementTimeout(null);
      await connection.rollback();
      expect(await scalar(connection, 'SELECT 8'), 8);
    });

    test('an update past its timeout', () async {
      await connection.setStatementTimeout(const Duration(milliseconds: 200));
      final error = await translated(
        () => connection.update('SELECT pg_sleep(5)'),
      );
      expect(error, isA<QueryTimeoutException>());
    });
  });

  group('errors', () {
    late JdbcConnection connection;
    late String schema;

    setUp(() async {
      schema = await newSchema();
      connection = await serverConnection(query: 'currentSchema=$schema');
      await connection.execute('''
CREATE TABLE authors (id INT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE books (
  id INT PRIMARY KEY,
  isbn TEXT CONSTRAINT books_isbn_key UNIQUE,
  author INT CONSTRAINT books_author_fkey REFERENCES authors (id),
  pages INT CONSTRAINT books_pages_check CHECK (pages > 0)
);
INSERT INTO authors VALUES (1, 'Herbert');
INSERT INTO books VALUES (1, 'x', 1, 10);
''');
    });

    test('a duplicate key names its constraint and hides the value', () async {
      final error = await sqlError(
        () => connection.update('INSERT INTO books (id, isbn) VALUES (?, ?)', [
          2,
          'x',
        ]),
      );
      expect(error.sqlState, '23505');
      expect(error.constraint, 'books_isbn_key');
      expect(error.sql, 'INSERT INTO books (id, isbn) VALUES (?, ?)');
      final exception = dialect.translate(error);
      expect(exception, isA<DuplicateKeyException>());
      expect((exception as DuplicateKeyException).constraint, 'books_isbn_key');
    });

    test('a duplicate primary key', () async {
      final error = await translated(
        () => connection.update('INSERT INTO books (id) VALUES (?)', [1]),
      );
      expect(error, isA<DuplicateKeyException>());
    });

    test('foreign key, not null and check violations', () async {
      for (final (sql, parameters) in [
        ('INSERT INTO books (id, author) VALUES (?, ?)', [3, 99]),
        ('INSERT INTO authors (id, name) VALUES (?, ?)', [3, null]),
        ('INSERT INTO books (id, pages) VALUES (?, ?)', [3, 0]),
        ('DELETE FROM authors WHERE id = ?', [1]),
      ]) {
        final error = await translated(
          () => connection.update(sql, parameters),
        );
        expect(
          error,
          isA<DataIntegrityViolationException>(),
          reason: sql,
        );
        expect(error, isNot(isA<DuplicateKeyException>()), reason: sql);
      }
    });

    test('wrong SQL', () async {
      expect(
        await translated(() => connection.query('SELECT * FROM nope')),
        isA<BadSqlGrammarException>(),
      );
      expect(
        await translated(() => connection.query('SELECT nope FROM books')),
        isA<BadSqlGrammarException>(),
      );
      expect(
        await translated(() => connection.query('SELEKT 1')),
        isA<BadSqlGrammarException>(),
      );
      expect(
        await translated(() => connection.query('SELECT nope()')),
        isA<BadSqlGrammarException>(),
      );
    });

    test('a value of the wrong type does not appear in the message', () async {
      final error = await sqlError(
        () => connection.query('SELECT * FROM books WHERE id = ?', [
          'hunter2',
        ]),
      );
      expect(error.sqlState, '22P02');
      expect(error.message, isNot(contains('hunter2')));
      expect('$error', isNot(contains('hunter2')));
      expect(
        dialect.translate(error),
        isA<DataIntegrityViolationException>(),
      );
    });

    test('a value of a type the driver cannot send', () async {
      final error = await sqlError(
        () => connection.query('SELECT ?', [Object()]),
      );
      expect(error.message, isNot(contains("Instance of 'Object'")));
    });

    test('the connection killed by the server: a lost connection', () async {
      final victim = await serverConnection();
      final pid = await scalar(victim, 'SELECT pg_backend_pid()');
      await connection.query('SELECT pg_terminate_backend(?)', [pid]);
      final error = await sqlError(() => victim.query('SELECT 1'));
      expect(error.connectionLost, isTrue);
      expect(
        dialect.translate(error),
        isA<DataAccessResourceFailureException>(),
      );
      expect(victim.isClosed, isTrue);
      expect(await victim.isValid(), isFalse);
    });

    test('a failed statement outside a transaction leaves the connection '
        'usable', () async {
      await expectLater(
        connection.query('SELECT * FROM nope'),
        throwsA(isA<SqlError>()),
      );
      expect(await scalar(connection, 'SELECT 1'), 1);
    });
  });

  group('the pool', () {
    test('hands out working connections, drops a killed one', () async {
      final source = await newPostgresSource(maxSize: 2);
      final first = await source.getConnection();
      final pid = await scalar(first, 'SELECT pg_backend_pid()');
      await source.releaseConnection(first);
      final admin = await serverConnection();
      await admin.query('SELECT pg_terminate_backend(?)', [pid]);
      // The pool validates before it hands a connection out.
      await Future<void>.delayed(const Duration(milliseconds: 200));
      final second = await source.getConnection();
      expect(await scalar(second, 'SELECT 1'), 1);
      expect(await scalar(second, 'SELECT pg_backend_pid()'), isNot(pid));
      await source.releaseConnection(second);
    });

    test('connections share the database but not the transactions', () async {
      final source = await newPostgresSource(maxSize: 2);
      final a = await source.getConnection();
      final b = await source.getConnection();
      await a.execute('CREATE TABLE t (n INT)');
      await a.begin();
      await a.update('INSERT INTO t VALUES (1)');
      expect(await scalar(b, 'SELECT count(*) FROM t'), 0);
      await a.commit();
      expect(await scalar(b, 'SELECT count(*) FROM t'), 1);
      await source.releaseConnection(a);
      await source.releaseConnection(b);
    });
  });
