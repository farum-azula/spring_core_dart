// PostgresDialect without a database: SQL text, column types, the values it
// converts and the translation of every SQL state.
import 'dart:typed_data';

import 'package:spring_boot_starter_data/spring_boot_starter_data.dart';
import 'package:test/test.dart';

enum Color { red }

DataAccessException _translate(
  String state, {
  String? constraint,
  bool lost = false,
}) => const PostgresDialect().translate(
  SqlError(
    'boom',
    sqlState: state,
    constraint: constraint,
    connectionLost: lost,
  ),
  sql: 'select ?',
);

void main() {
  const dialect = PostgresDialect();

  test('names, quoting and clauses', () {
    expect(dialect.name, 'postgresql');
    expect(dialect.quote('order'), '"order"');
    expect(dialect.quote('a"b'), '"a""b"');
    expect(dialect.table('book', 'shop'), '"shop"."book"');
    expect(dialect.limitOffset(10, 20), 'LIMIT 10 OFFSET 20');
    expect(dialect.limitOffset(10, null), 'LIMIT 10');
    expect(dialect.limitOffset(null, 5), 'OFFSET 5');
    expect(dialect.limitOffset(null, null), isEmpty);
    expect(dialect.lower('"title"'), 'lower("title")');
    expect(dialect.likeIgnoresCase, isFalse);
    expect(dialect.supportsSavepoints, isTrue);
    expect(dialect.supportsForwardForeignKeys, isFalse);
    expect(dialect.beforeDropStatements, isEmpty);
  });

  test('identity ids', () {
    expect(
      dialect.identityColumn(const ClassType<int>()),
      'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    );
  });

  test('row locks, NOWAIT, SKIP LOCKED and the lock timeout', () {
    expect(dialect.lockStrategy, LockStrategy.rowLocks);
    expect(dialect.lockClause(LockMode.pessimisticWrite), 'FOR UPDATE');
    expect(dialect.lockClause(LockMode.pessimisticRead), 'FOR SHARE');
    expect(
      dialect.lockClause(LockMode.pessimisticWrite, timeout: Duration.zero),
      'FOR UPDATE NOWAIT',
    );
    expect(
      dialect.lockClause(LockMode.pessimisticRead, skipLocked: true),
      'FOR SHARE SKIP LOCKED',
    );
    // The server refuses both words at once: skipping wins.
    expect(
      dialect.lockClause(
        LockMode.pessimisticWrite,
        timeout: Duration.zero,
        skipLocked: true,
      ),
      'FOR UPDATE SKIP LOCKED',
    );
    // A wait is a statement before the query, never a clause.
    expect(
      dialect.lockClause(
        LockMode.pessimisticWrite,
        timeout: const Duration(seconds: 2),
      ),
      'FOR UPDATE',
    );
    expect(
      dialect.lockTimeoutStatement(const Duration(seconds: 2)),
      "SET LOCAL lock_timeout = '2000ms'",
    );
    // 0 would switch the timeout off.
    expect(
      dialect.lockTimeoutStatement(const Duration(microseconds: 10)),
      "SET LOCAL lock_timeout = '1ms'",
    );
    expect(dialect.writeLockStatement, isNull);
  });

  test('migration lock and transactional DDL', () {
    expect(dialect.migrationLock, startsWith('SELECT pg_advisory_lock('));
    expect(dialect.migrationUnlock, startsWith('SELECT pg_advisory_unlock('));
    // The same key locks and unlocks.
    expect(
      RegExp(r'\((\d+)\)').firstMatch(dialect.migrationLock!)![1],
      RegExp(r'\((\d+)\)').firstMatch(dialect.migrationUnlock!)![1],
    );
  });

  test('drop and foreign keys', () {
    expect(
      dialect.dropTableStatement('books'),
      'DROP TABLE IF EXISTS "books"',
    );
    expect(
      dialect.dropTableStatement('books', schema: 'shop', referenced: true),
      'DROP TABLE IF EXISTS "shop"."books" CASCADE',
    );
    expect(
      dialect.addForeignKeyStatement(
        name: 'fk_books_author',
        table: 'books',
        schema: null,
        column: 'author',
        parentTable: 'authors',
        parentSchema: null,
        parentColumn: 'id',
        onDelete: OnDeleteAction.cascade,
      ),
      'ALTER TABLE "books" ADD CONSTRAINT "fk_books_author" FOREIGN KEY '
      '("author") REFERENCES "authors" ("id") ON DELETE CASCADE',
    );
    expect(dialect.onDeleteClause(OnDeleteAction.noAction), isEmpty);
    expect(
      dialect.onDeleteClause(OnDeleteAction.setNull),
      ' ON DELETE SET NULL',
    );
  });

  test('column types', () {
    final types = <TypeInfo<Object?>, String?>{
      const ClassType<int>(): 'BIGINT',
      const ClassType<bool>(): 'BOOLEAN',
      const ClassType<double>(): 'DOUBLE PRECISION',
      const ClassType<num>(): 'DOUBLE PRECISION',
      const ClassType<String>(): 'TEXT',
      const EnumType<Color>(Color.values): 'TEXT',
      const ClassType<DateTime>(): 'TIMESTAMPTZ',
      const ClassType<BigInt>(): 'NUMERIC',
      const ClassType<Uint8List>(): 'BYTEA',
      const ListType<int>(ClassType<int>()): 'BYTEA',
      const ListType<String>(ClassType<String>()): null,
    };
    for (final MapEntry(key: type, value: column) in types.entries) {
      expect(dialect.columnType(type), column, reason: '$type');
    }
  });

  test('columns fit by the types information_schema reports', () {
    const integer = ClassType<int>();
    const text = ClassType<String>();
    const real = ClassType<double>();
    const flag = ClassType<bool>();
    const moment = ClassType<DateTime>();
    for (final width in ['smallint', 'integer', 'bigint']) {
      expect(dialect.columnFits(width, integer), isTrue, reason: width);
    }
    expect(dialect.columnFits('numeric', integer), isFalse);
    expect(dialect.columnFits('text', integer), isFalse);
    expect(dialect.columnFits('character varying(40)', text), isTrue);
    expect(dialect.columnFits('text', text), isTrue);
    expect(dialect.columnFits('uuid', text), isTrue);
    expect(dialect.columnFits('boolean', text), isFalse);
    expect(
      dialect.columnFits('text', const EnumType<Color>(Color.values)),
      isTrue,
    );
    expect(dialect.columnFits('double precision', real), isTrue);
    expect(dialect.columnFits('real', real), isTrue);
    expect(dialect.columnFits('numeric', real), isTrue);
    expect(dialect.columnFits('bigint', real), isFalse);
    expect(dialect.columnFits('boolean', flag), isTrue);
    expect(dialect.columnFits('bigint', flag), isFalse);
    expect(dialect.columnFits('timestamp with time zone', moment), isTrue);
    expect(
      dialect.columnFits('timestamp without time zone', moment),
      isTrue,
    );
    expect(dialect.columnFits('date', moment), isTrue);
    expect(dialect.columnFits('text', moment), isFalse);
    expect(dialect.columnFits('bytea', const ClassType<Uint8List>()), isTrue);
    expect(dialect.columnFits('text', const ClassType<Uint8List>()), isFalse);
    expect(dialect.columnFits('numeric', const ClassType<BigInt>()), isTrue);
    // A type with no column.
    expect(dialect.columnFits('text', const ClassType<Object>()), isFalse);
  });

  test('every isolation level is offered', () {
    expect(dialect.isolationLevels, Isolation.values.toSet());
  });

  test('DEFAULT literals', () {
    expect(dialect.defaultLiteral(null), 'NULL');
    expect(dialect.defaultLiteral(true), 'TRUE');
    expect(dialect.defaultLiteral(false), 'FALSE');
    expect(dialect.defaultLiteral(3), '3');
    expect(dialect.defaultLiteral(1.5), '1.5');
    expect(dialect.defaultLiteral("it's"), "'it''s'");
    expect(dialect.defaultLiteral(Color.red), "'red'");
    expect(dialect.defaultLiteral(double.nan), isNull);
    expect(dialect.defaultLiteral([1]), isNull);
  });

  group('values', () {
    test('to the database: UTC instants, text for a BigInt, native bool', () {
      final local = DateTime(2026, 3, 1, 10);
      expect(dialect.toDatabase(local), local.toUtc());
      expect((dialect.toDatabase(local)! as DateTime).isUtc, isTrue);
      expect(
        dialect.toDatabase(BigInt.parse('12345678901234567890')),
        '12345678901234567890',
      );
      expect(dialect.toDatabase(true), true);
      expect(dialect.toDatabase(5), 5);
      expect(dialect.toDatabase([1, 2]), isA<Uint8List>());
      final bytes = Uint8List.fromList([1]);
      expect(dialect.toDatabase(bytes), same(bytes));
    });

    test('from the database', () {
      Object? read(Object? value, TypeInfo<Object?> type) =>
          dialect.fromDatabase(value, type);
      expect(read(null, const ClassType<int>()), isNull);
      final utc = DateTime.utc(2026, 3, 1, 10);
      expect(read(utc, const ClassType<DateTime>()), utc);
      expect(
        read(DateTime(2026, 3, 1, 10), const ClassType<DateTime>()),
        isA<DateTime>().having((d) => d.isUtc, 'isUtc', isTrue),
      );
      expect(read('2026-03-01T10:00:00Z', const ClassType<DateTime>()), utc);
      expect(
        read(1772359200000, const ClassType<DateTime>()),
        DateTime.fromMillisecondsSinceEpoch(1772359200000, isUtc: true),
      );
      expect(read(true, const ClassType<bool>()), isTrue);
      expect(read(0, const ClassType<bool>()), isFalse);
      expect(read('t', const ClassType<bool>()), isTrue);
      // numeric comes as text.
      expect(read('42', const ClassType<int>()), 42);
      expect(read(BigInt.two, const ClassType<int>()), 2);
      expect(read('1.5', const ClassType<double>()), 1.5);
      expect(read(2, const ClassType<double>()), 2.0);
      expect(read('NaN', const ClassType<double>()), isNaN);
      expect(read('2.5', const ClassType<num>()), 2.5);
      expect(
        read('123456789012345678901234567890', const ClassType<BigInt>()),
        BigInt.parse('123456789012345678901234567890'),
      );
      expect(read('7.00', const ClassType<BigInt>()), BigInt.from(7));
      expect(read(7, const ClassType<BigInt>()), BigInt.from(7));
      expect(
        read([1, 2], const ClassType<Uint8List>()),
        isA<Uint8List>().having((b) => b, 'bytes', [1, 2]),
      );
      expect(read('x', const ClassType<String>()), 'x');
    });
  });

  group('errors by SQL state', () {
    test('duplicate keys carry the constraint', () {
      final error = _translate('23505', constraint: 'books_isbn_key');
      expect(error, isA<DuplicateKeyException>());
      expect((error as DuplicateKeyException).constraint, 'books_isbn_key');
      expect(error.sql, 'select ?');
    });

    test('integrity violations: foreign key, not null, check, others', () {
      for (final state in ['23503', '23502', '23514', '23P01', '23000']) {
        final error = _translate(state);
        expect(error, isA<DataIntegrityViolationException>(), reason: state);
        expect(error, isNot(isA<DuplicateKeyException>()), reason: state);
      }
    });

    test('data exceptions are integrity violations too', () {
      for (final state in ['22001', '22003', '22P02', '22007']) {
        expect(
          _translate(state),
          isA<DataIntegrityViolationException>(),
          reason: state,
        );
      }
    });

    test('a LIKE pattern ending with the escape and a NUL are api misuse', () {
      for (final state in ['22025', '22021']) {
        final error = _translate(state);
        expect(
          error,
          isA<InvalidDataArgumentException>(),
          reason: state,
        );
        expect(error, isNot(isA<DataIntegrityViolationException>()));
      }
    });

    test('concurrency: serialization, deadlock, lock not had, timeout', () {
      expect(
        _translate('40001'),
        isA<CannotSerializeTransactionException>(),
      );
      expect(_translate('40P01'), isA<DeadlockLoserDataAccessException>());
      expect(_translate('55P03'), isA<CannotAcquireLockException>());
      expect(_translate('57014'), isA<QueryTimeoutException>());
      // All of them are pessimistic locking failures, which retry.
      expect(
        _translate('40001'),
        isA<PessimisticLockingFailureException>(),
      );
    });

    test('wrong SQL', () {
      for (final state in [
        '42601',
        '42P01',
        '42703',
        '42883',
        '42804',
        '42P18',
      ]) {
        expect(_translate(state), isA<BadSqlGrammarException>(), reason: state);
      }
      // Other class 42 errors (a duplicate table, a privilege).
      final other = _translate('42P07');
      expect(other, isA<InvalidDataAccessResourceUsageException>());
      expect(other, isNot(isA<BadSqlGrammarException>()));
      expect(
        _translate('25006'),
        isA<InvalidDataAccessResourceUsageException>(),
      );
    });

    test('insufficient privilege is a permission error, not wrong SQL', () {
      final denied = _translate('42501');
      expect(denied, isA<PermissionDeniedDataAccessException>());
      expect(denied, isA<NonTransientDataAccessException>());
      expect(denied, isNot(isA<InvalidDataAccessResourceUsageException>()));
      expect(denied.message, contains('boom'));
      expect(denied.sql, 'select ?');
      expect(denied.cause, isA<SqlError>());
      // Its neighbours in class 42 keep their translation.
      expect(_translate('42601'), isA<BadSqlGrammarException>());
      expect(
        _translate('42P07'),
        isA<InvalidDataAccessResourceUsageException>(),
      );
    });

    test('functions are called by name, with named notation', () {
      expect(dialect.supportsFunctions, isTrue);
      expect(
        dialect.functionCall('total', const []),
        'select * from "total"()',
      );
      expect(
        dialect.functionCall('app.transfer', const ['from_id', 'amount']),
        'select * from "app"."transfer"("from_id" => ?, "amount" => ?)',
      );
    });

    test('connection, authentication, shutdown and resources', () {
      for (final state in [
        '08000',
        '08006',
        '08001',
        '28P01',
        '28000',
        '57P01',
        '53300',
        '3D000',
      ]) {
        expect(
          _translate(state),
          isA<DataAccessResourceFailureException>(),
          reason: state,
        );
      }
    });

    test('no SQL state: a lost connection, else an uncategorized error', () {
      expect(
        dialect.translate(const SqlError('gone', connectionLost: true)),
        isA<DataAccessResourceFailureException>(),
      );
      expect(
        dialect.translate(const SqlError('odd')),
        isA<UncategorizedSqlException>(),
      );
      expect(_translate('XX000'), isA<UncategorizedSqlException>());
    });

    test("the message is the error's and the cause is kept", () {
      const error = SqlError('relation "x" does not exist', sqlState: '42P01');
      final translated = dialect.translate(error);
      expect(translated.message, error.message);
      expect(translated.cause, same(error));
    });
  });
}
