/// The same tables for PostgreSQL: identity ids, `bigint`, `double
/// precision`, `boolean` for the flag and `timestamptz` for the instants.
final List<String> postgresSchema = [
  for (final statement in schema)
    statement
        .replaceAll(
          'integer primary key',
          'bigint generated by default as identity primary key',
        )
        .replaceAll(' integer', ' bigint')
        .replaceAll(' real', ' double precision')
        .replaceAll('in_stock bigint', 'in_stock boolean')
        .replaceAll('released text', 'released timestamptz')
        .replaceAll('stamp text', 'stamp timestamptz'),
];

