  SqlCrates get sqlCrates => context.getBean<SqlCrates>();
  SqlMembers get sqlMembers => context.getBean<SqlMembers>();
  SqlGauges get sqlGauges => context.getBean<SqlGauges>();
  MemoryGauges get memoryGauges => context.getBean<MemoryGauges>();
}

final class _Holder {
  PooledDataSource? dataSource;
  JdbcDataStore? store;
}

/// Starts the application with a SQLite data source (a PostgreSQL one with
/// [postgres], in a schema of its own: see `../../postgres/support.dart`) and
/// calls [body].
///
/// Without [file] the database is a private in-memory one and the pool has
/// one connection (the database lives in it); with a [file] (a path), the
/// pool has [connections] connections on the same database. [properties]
/// are added to the environment.
Future<void> withJdbc(
  FutureOr<void> Function(Jdbc jdbc) body, {
  String? file,
  int connections = 1,
  List<String> properties = const [],
  JdbcLogSettings logSettings = const JdbcLogSettings(),
  Map<String, String> driverProperties = const {},
  bool postgres = false,
  ConnectionSettings? postgresSettings,
}) async {
  final holder = _Holder();
  // [postgresSettings]: a database of the caller's (the transaction matrix
  // has one of its own), instead of a schema in the shared one.
  final schemaName = postgres && postgresSettings == null
      ? await pg.newSchema()
      : null;
  final wiring = BeanModule('jdbcWiring', [
    BeanDefinition<RepositoryFactory>(
      name: 'repositoryFactory',
      create: (r) {
        final dataSource = PooledDataSource(
          name: 'test',
          driver: r.dependency<JdbcDriver>(
            name: postgres ? 'postgresJdbcDriver' : 'sqlite3JdbcDriver',
          ),
          settings:
              postgresSettings ??
              (schemaName != null
                  ? pg.schemaSettings(schemaName, properties: driverProperties)
                  : ConnectionSettings(
                      url: Uri.parse(
                        file == null ? 'sqlite::memory:' : 'sqlite:file:$file',
                      ),
                      properties: driverProperties,
                    )),
          pool: PoolSettings(
            maxSize: connections,
            connectionTimeout: const Duration(seconds: 5),
          ),
        );
        holder.dataSource = dataSource;
        final factory = RepositoryFactory(
          mappingContext: r.dependency<RelationalMappingContext>(),
          converter: r.dependency<EntityConverter>(),
          jdbcDataSources: {RepositoryFactory.primaryDataSource: dataSource},
          jdbcLogSettings: logSettings,
          environment: r.dependency<Environment>(),
          beanFactory: r.dependency<BeanFactory>(),
        );
        return factory;
      },
    ),
  ]);
  await const ApplicationContextRunner()
      .withUserConfiguration($application)
      .withAutoConfiguration(springBootStarterDataAutoConfiguration)
      .withUserConfiguration(wiring)
      .withPropertyValues(properties)
      .runAsync((context) async {
        if (context.startupFailure case final failure?) {
          throw StateError('The application did not start: $failure');
        }
        final dataSource = holder.dataSource!;
        holder.store = context.getBean<RepositoryFactory>().jdbcStoreFor();
        final setup = JdbcTemplate(dataSource);
        if (file == null || !File(file).existsSync()) {
          for (final statement in postgres ? postgresSchema : schema) {
            await setup.execute(statement);
          }
          // The tables of the references are the ones the starter writes
          // from the annotations: foreign keys, indexes, unique keys.
          final mapping = context.getBean<RelationalMappingContext>();
          await SchemaCreator(dataSource).create([
            for (final type in referenceTypes)
              mapping.getRequiredPersistentEntityOfType(type),
          ]);
        }
        try {
          await body(Jdbc._(context, dataSource, holder));
        } finally {
          await dataSource.close();
        }
      });
}

/// A temporary directory to delete with [deleteTemp].
Directory newTemp() => Directory.systemTemp.createTempSync('jdbc_store_test');

/// Deletes [directory].
void deleteTemp(Directory directory) {
  if (directory.existsSync()) {
    directory.deleteSync(recursive: true);
  }
}

/// The ids of [books], in order.
List<int?> ids(Iterable<Book> books) => [for (final b in books) b.id];

/// The titles of [books], in order.
List<String> titles(Iterable<Book> books) => [for (final b in books) b.title];

/// The author reference of id [id].
AggregateReference<Author, int> author(int id) =>
    AggregateReference<Author, int>(id);

/// What a future ends with: its value, or the error it failed with.
Future<Object?> outcome(Future<Object?> future) =>
    future.then<Object?>((value) => value, onError: (Object error) => error);

/// A UTC moment on [year]-[month]-[day].
DateTime day(int year, int month, int day) =>
    DateTime.utc(year, month, day, 12, 30, 15, 250);

