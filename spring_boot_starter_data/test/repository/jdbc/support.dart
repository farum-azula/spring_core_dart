/// A running application on both stores: the memory repositories and the
/// SQL ones, over a SQLite data source whose tables exist.
final class Jdbc {
  Jdbc._(this.context, this.dataSource, this._holder);

  final AssertableApplicationContext context;

  /// The SQL data source of the SQL repositories.
  final PooledDataSource dataSource;

  final _Holder _holder;

  /// A template on the data source, for what the tests set up by hand.
  JdbcTemplate get jdbc => JdbcTemplate(dataSource);

  /// The factory the repositories were made by.
  RepositoryFactory get factory => context.getBean<RepositoryFactory>();

  /// The SQL store of the primary data source.
  JdbcDataStore get store => _holder.store!;

  /// The mapping context of the application.
  RelationalMappingContext get mapping =>
      context.getBean<RelationalMappingContext>();

  PersistentEntity<T> entity<T extends Object>() =>
      mapping.getRequiredPersistentEntity<T>();

  /// The transaction manager the SQL repositories' writes run in.
  DataSourceTransactionManager get transactions => store.transactionManager;

  /// A template for transactions of the SQL data source.
  TransactionTemplate transaction([
    TransactionDefinition definition = TransactionDefinition.defaults,
  ]) => TransactionTemplate(transactions, definition);

  MemoryBooks get memoryBooks => context.getBean<MemoryBooks>();
  SqlBooks get sqlBooks => context.getBean<SqlBooks>();
  MemoryOrders get memoryOrders => context.getBean<MemoryOrders>();
  SqlOrders get sqlOrders => context.getBean<SqlOrders>();
  MemoryShelves get memoryShelves => context.getBean<MemoryShelves>();
  SqlShelves get sqlShelves => context.getBean<SqlShelves>();
  MemoryAccounts get memoryAccounts => context.getBean<MemoryAccounts>();
  SqlAccounts get sqlAccounts => context.getBean<SqlAccounts>();
  MemoryTickets get memoryTickets => context.getBean<MemoryTickets>();
  SqlTickets get sqlTickets => context.getBean<SqlTickets>();
  MemoryNotes get memoryNotes => context.getBean<MemoryNotes>();
  SqlNotes get sqlNotes => context.getBean<SqlNotes>();
  MemoryAuthors get memoryAuthors => context.getBean<MemoryAuthors>();
  SqlAuthors get sqlAuthors => context.getBean<SqlAuthors>();
