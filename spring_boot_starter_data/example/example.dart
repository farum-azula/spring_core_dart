/// A service on the repositories; its transactions are SQL transactions of
/// the application's database (the data source's manager) or, without one,
/// of the in-memory store.
@Service()
class Library {
  Library(this.authors, this.books, this.orders, this.bookmarks);

  final AuthorRepository authors;
  final BookRepository books;
  final PurchaseOrderRepository orders;
  final BookmarkRepository bookmarks;

  @Transactional()
  Future<Book> add(String title, int year, {String? author}) async {
    final writer = author == null
        ? null
        : await authors.save(Author(name: author));
    return await books.save(
      Book(
        title: title,
        year: year,
        author: writer == null
            ? null
            : AggregateReference<Author, int>(writer.id!),
      ),
    );
  }

  /// Removes a book; its bookmarks go with it (`on delete cascade`).
  @Transactional()
  Future<void> discard(int bookId) => books.deleteById(bookId);

  /// Renames a book: the row is locked by the first statement, so two
  /// renames of one book run one after the other, and `@Version` still
  /// catches a change made outside the lock.
  @Transactional()
  Future<Book?> rename(int year, String title, String newTitle) async {
    final book = await books.findOneByYearAndTitle(year, title);
    if (book == null) {
      return null;
    }
    book.title = newTitle;
    return await books.save(book);
  }

  /// Books of a decade, oldest first.
  @Transactional(readOnly: true)
  Future<List<Book>> decade(int start) async {
    final found = await books.findByYearBetween(start, start + 9);
    return found..sort((a, b) => a.year.compareTo(b.year));
  }

  @Transactional()
  Future<PurchaseOrder> order(String customer, Map<String, int> quantities) =>
      orders.save(
        PurchaseOrder(
          customer: customer,
          lines: [
            for (final MapEntry(:key, :value) in quantities.entries)
              OrderLine(sku: key, quantity: value),
          ],
        ),
      );
}

/// Uses the library and logs what it saw; `@Log` gives it the `log` getter.
@Component()
@Log(topic: 'example')
@Order(1)
class LibraryTour implements CommandLineRunner {
  LibraryTour(this.library);

  final Library library;

  @override
  Future<void> run(List<String> args) async {
    await library.add('Dune', 1965, author: 'Frank Herbert');
    await library.add('Neuromancer', 1984, author: 'William Gibson');
    final saved = await library.add('Snow Crash', 1992, author: 'Neal');
    await library.rename(1992, 'Snow Crash', 'Snow Crash (1992)');
    log.info('saved ${saved.title} as #${saved.id}, version ${saved.version}');

    final nineties = await library.decade(1990);
    log.info('the nineties: ${nineties.map((b) => b.title).join(', ')}');

    // A bookmark references its book; deleting the book deletes it too.
    final draft = await library.add('Draft', 2001);
    await library.bookmarks.save(Bookmark(bookId: draft.id!, page: 42));
    await library.discard(draft.id!);
    log.info('bookmarks left: ${await library.bookmarks.count()}');

    final order = await library.order('Ada', {'dune-hc': 1, 'snow-pb': 2});
    final loaded = await library.orders.findById(order.id!);
    log.info('order of ${loaded!.customer}: ${loaded.lines.length} lines');
  }
}

/// Reads with the `@Query` join, the `JdbcClient` and the view of the
/// repeatable migration; only with a database.
@Component()
@Log(topic: 'example')
@Order(2)
@ConditionalOnProperty('spring.datasource.url')
class ReportTour implements CommandLineRunner {
  ReportTour(this.reports, this.jdbc);

  final BookReportRepository reports;
  final JdbcClient jdbc;

  @override
  Future<void> run(List<String> args) async {
    for (final card in await reports.cardsSince(1980)) {
      log.info('$card');
    }
    final counts = await jdbc
        .sql('select name, books from author_book_counts order by name')
        .query<String>((row) => '${row['name']}: ${row['books']} book(s)')
        .list();
    counts.forEach(log.info);
  }
}

