/// The root widget of a Flutter app built on Spring: it starts the
/// application context and gives it to every widget below.
///
/// Pass it to `runApp`. While the application starts (configuration files,
/// beans, runners, font files) it shows [splash]; if the start fails, it
/// shows [failure] and logs the report. Once the context is ready, the
/// widgets below get their beans through it (`context.bean<T>()`, the
/// generated getters, `SpringStatelessWidget` and `SpringStatefulWidget`).
///
/// With [home] it also builds the app widget from the configuration: a
/// [SpringApp], which is a `WidgetsApp`, `MaterialApp` or `CupertinoApp`
/// depending on `spring.flutter.app.type`, with the title, debug banner,
/// locales and themes of the properties. With [child] the app writes its
/// own `MaterialApp` (or other app widget) instead.
///
/// ```dart
/// import 'main.spring.dart';
///
/// @SpringBootApplication()
/// void main() => runApp(
///   SpringApplicationWidget(
///     application: () => springApplication, // generated by build_runner
///     home: const CounterPage(),            // the app widget from properties
///   ),
/// );
/// ```
///
/// What it does besides starting the application:
///
/// - The platform is an active profile ([platformProfiles]): `android` and
///   `mobile` on Android, `web` in a browser, `macos` and `desktop` on a
///   Mac, and so on. So `application-android.properties` and
///   `@Profile(['ios'])` beans just work.
/// - The OS environment is not read: on a phone it is noise, and values
///   come from `--dart-define` instead. A build that defines
///   `spring.flutter.scan-os-environment=true` reads it.
/// - A hot reload restarts the context when the generated code changed
///   (new or changed beans, annotations, `lib/resources/`), like Spring
///   Boot DevTools' restart, and builds the widgets below afresh. When only
///   method bodies changed, the context and the beans' state stay. After
///   such a restart the runners run again only with
///   [rerunRunnersOnReload]; `spring.devtools.restart.enabled=false` turns
///   the restarts off.
/// - Each change of the app's lifecycle is published as an
///   [AppLifecycleStateEvent]. In the background the context is paused
///   (`@Scheduled` tasks and WebSocket connections stop) and it restarts
///   when the app comes back, unless
///   `spring.flutter.lifecycle.pause-in-background=false`.
/// - the context is closed when this widget is removed.
///
/// Spring (Java) has no widget; the nearest is the `main` method of a
/// Spring Boot app, `SpringApplication.run(App.class, args)`.
class SpringApplicationWidget extends StatefulWidget {
  /// Runs the application [application] returns, then shows [home] in a
  /// [SpringApp] or shows [child]. Exactly one of [home] and [child] must
  /// be given.
  const SpringApplicationWidget({
    required this.application,
    this.child,
    this.home,
    this.splash,
    this.failure,
    this.args = const [],
    this.rerunRunnersOnReload = false,
    super.key,
  }) : assert(
         (child == null) != (home == null),
         'SpringApplicationWidget needs a home or a child, not both',
       );

  /// Returns the application to run: `() => springApplication`, the
  /// variable the generator writes into `main.spring.dart`. It is a
  /// function, not the value, so that a hot reload can fetch the new
  /// generated code and restart the context with it.
  final SpringApplication Function() application;

  /// The app, shown once the application has started, for an app that
  /// builds its own app widget (`MaterialApp`, ...). Not together with
  /// [home].
  final Widget? child;

  /// The first page of a [SpringApp] built from the configuration, shown
  /// once the application has started. Not together with [child].
  final Widget? home;

  /// Builds what is shown while the application starts, such as a logo;
  /// an empty box by default.
  final WidgetBuilder? splash;

  /// Builds what is shown when the start (or a restart after a hot reload)
  /// fails, from the error. By default a plain screen shows the error (in
  /// release builds only a short note). The failure is logged either way.
  final Widget Function(BuildContext context, Object error)? failure;

  /// Command-line arguments, read as properties (`--name=value`), for
  /// desktop apps started with some; none by default.
  final List<String> args;

  /// Whether `ApplicationRunner` / `CommandLineRunner` beans run again
  /// when a hot reload restarts the context, as with Spring Boot DevTools.
  /// `false` by default: the app did not really start again.
  final bool rerunRunnersOnReload;

  @override
  State<SpringApplicationWidget> createState() =>
      _SpringApplicationWidgetState();
}

class _SpringApplicationWidgetState extends State<SpringApplicationWidget> {
  ConfigurableApplicationContext? _context;
  Object? _error;
  late final AppLifecycleListener _lifecycle;
  bool _paused = false;
  Future<void> _lifecycleWork = Future.value();

  @override
  void initState() {
    super.initState();
    _lifecycle = AppLifecycleListener(onStateChange: _onLifecycle);
    unawaited(_start());
  }

  Future<void> _start() async {
    ConfigurableApplicationContext? started;
    try {
      // `asset:` resources: exists() needs the asset manifest.
      await AssetProtocolResolver.loadRootManifest();
      final application = widget.application();
      final context = started = await application.runAsync(
        widget.args,
        systemEnvironment: _scanOsEnvironment(application) ? null : const {},
        additionalProfiles: platformProfiles(),
      );
      SpringWidgetBindings.check(context);
      _checkApp(context);
      await _loadFonts(context);
      if (!mounted) {
        await context.closeAsync();
        return;
      }
      setState(() => _context = context);
    } catch (error) {
      // The application started, then a check of the widget failed: its
      // runners and scheduled tasks must not go on behind the failure
      // screen (and a hot reload's retry starts a new one).
      if (started != null) {
        await _closeQuietly(started);
      }
      if (mounted) {
        setState(() => _error = error);
      }
    }
  }

  static Future<void> _closeQuietly(
    ConfigurableApplicationContext context,
  ) async {
    if (!context.isActive) {
      return;
    }
    try {
      await context.closeAsync();
    } catch (error, stackTrace) {
      FlutterError.reportError(
        FlutterErrorDetails(
          exception: error,
          stack: stackTrace,
          library: 'spring_boot_starter_flutter',
          context: ErrorDescription(
            'while closing the application context after a failed start',
          ),
        ),
      );
    }
  }

  // An invalid `spring.flutter.app.*` value fails the start.
  void _checkApp(ApplicationContext context) {
    if (widget.home != null) {
      FlutterAppSettings.of(context);
      ThemeSelection.of(context); // reads and checks every theme
    }
  }

  // The app's font files, before the first frame.
  static Future<void> _loadFonts(ApplicationContext context) {
    final manifest = AssetProtocolResolver.rootManifest;
    if (manifest == null) {
      return Future.value();
    }
    final themes = SpringThemes.of(context);
    return ThemeFonts.loadFor(
      context,
      rootBundle,
      manifest.listAssets(),
      themeFamilies: {
        for (final name in themes.names) ...themes.data(name).fontFamilies,
      },
    );
  }

  static bool _scanOsEnvironment(SpringApplication application) {
    final defines = application.dartDefines;
    final value =
        defines['spring.flutter.scan-os-environment'] ??
        defines['SPRING_FLUTTER_SCANOSENVIRONMENT'];
    return value?.trim().toLowerCase() == 'true';
  }

  @override
  void reassemble() {
    super.reassemble();
    final running = _context;
    if (running == null) {
      if (_error != null) {
        // The start failed: try again with the reloaded code.
        setState(() => _error = null);
        unawaited(_start());
      }
      return;
    }
    if (!_restartEnabled(running)) {
      return;
    }
    ConfigurableApplicationContext? restarted;
    try {
      final context = widget.application().reload(
        running,
        runners: widget.rerunRunnersOnReload,
      );
      if (!identical(context, running)) {
        restarted = context;
        SpringWidgetBindings.check(context);
        _checkApp(context);
        _paused = false;
        setState(() => _context = context);
      }
    } catch (error) {
      // The new context started, then a check failed: it is closed, and
      // so is the old one (reload closes it first; not when the reload
      // failed before), so the next reload's retry (_start) runs the
      // only context.
      if (restarted != null) {
        unawaited(_closeQuietly(restarted));
      }
      if (running.isActive) {
        unawaited(_closeQuietly(running));
      }
      setState(() {
        _context = null;
        _error = error;
      });
    }
  }

  void _onLifecycle(AppLifecycleState state) {
    final context = _context;
    if (context == null || !context.isActive) {
      return;
    }
    context.publishEvent(AppLifecycleStateEvent(context, state));
    final pause =
        state == AppLifecycleState.hidden || state == AppLifecycleState.paused;
    if ((!pause && state != AppLifecycleState.resumed) ||
        pause == _paused ||
        !_pauseInBackground(context)) {
      return;
    }
    _paused = pause;
    _lifecycleWork = _lifecycleWork.then((_) async {
      if (!context.isActive) {
        return;
      }
      try {
        if (pause) {
          await context.pauseAsync();
        } else {
          context.restart();
        }
      } catch (error, stackTrace) {
        FlutterError.reportError(
          FlutterErrorDetails(
            exception: error,
            stack: stackTrace,
            library: 'spring_boot_starter_flutter',
            context: ErrorDescription(
              pause
                  ? 'while pausing the application context'
                  : 'while restarting the application context',
            ),
          ),
        );
      }
    });
  }

  // Spring Boot DevTools' switch for restarts after code changes.
  static bool _restartEnabled(ConfigurableApplicationContext context) =>
      context.environment
          .getProperty('spring.devtools.restart.enabled')
          ?.trim()
          .toLowerCase() !=
      'false';

  static bool _pauseInBackground(ConfigurableApplicationContext context) =>
      context.environment
          .getProperty('spring.flutter.lifecycle.pause-in-background')
          ?.trim()
          .toLowerCase() !=
      'false';

  @override
  void dispose() {
    _lifecycle.dispose();
    final context = _context;
    _context = null;
    if (context != null && context.isActive) {
      unawaited(context.closeAsync());
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final error = _error;
    if (error != null) {
      return widget.failure?.call(context, error) ?? _Failure(error);
    }
    final running = _context;
    if (running == null) {
      return widget.splash?.call(context) ?? const SizedBox.shrink();
    }
    return SpringScope(
      applicationContext: running,
      // A new context starts the widgets afresh: none keeps a bean of the
      // closed one in its state.
      child: KeyedSubtree(
        key: ObjectKey(running),
        child: widget.child ?? SpringApp(home: widget.home!),
      ),
    );
  }
}

/// The default failure screen: the error in debug builds, a short note in
/// release builds (the details are in the log).
class _Failure extends StatelessWidget {
  const _Failure(this.error);

  final Object error;

  @override
  Widget build(BuildContext context) => Directionality(
    textDirection: TextDirection.ltr,
    child: ColoredBox(
      color: const Color(0xFFFFFFFF),
      child: SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: SingleChildScrollView(
            child: Text(
              kReleaseMode
                  ? 'The application failed to start.'
                  : 'The application failed to start:\n\n$error',
              style: const TextStyle(color: Color(0xFF000000), fontSize: 14),
            ),
          ),
        ),
      ),
    ),
  );
}
