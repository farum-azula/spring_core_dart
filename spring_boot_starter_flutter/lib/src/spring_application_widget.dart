/// The root widget of a Flutter app built on Spring: it starts the
/// application context and gives it to every widget below.
///
/// Pass it to `runApp`. While the application starts (configuration files,
/// beans, runners, font files) it shows [splash], or else the `splash` of
/// the active theme (`spring.flutter.theme.splash`: background, logo,
/// title and a loader that follows the start's progress, shown until the
/// context is ready and its `min-duration` is over, then faded out); if
/// the start fails, it
/// shows [failure] and logs the report. Once the context is ready, the
/// widgets below get their beans through it (`context.bean<T>()`, the
/// generated getters, `SpringStatelessWidget` and `SpringStatefulWidget`).
///
/// With [home] it also builds the app widget from the configuration: a
/// [SpringApp], which is a `WidgetsApp`, `MaterialApp` or `CupertinoApp`
/// depending on `spring.flutter.app.type`, with the title, debug banner,
/// locales and themes of the properties. With neither [home] nor [child]
/// the [SpringApp] is built on the application's router (the screens of
/// `spring_boot_starter_flutter_navigation`). With [child] the app writes
/// its own `MaterialApp` (or other app widget) instead.
///
/// ```dart
/// import 'spring_gen/main.spring.dart';
///
/// @SpringBootApplication()
/// void main() => runApp(
///   SpringApplicationWidget(
///     application: () => springApplication, // generated by build_runner
///     home: const CounterPage(),            // the app widget from properties
///   ),
/// );
/// ```
///
/// What it does besides starting the application:
///
/// - The platform is an active profile ([platformProfiles]): `android` and
///   `mobile` on Android, `web` in a browser, `macos` and `desktop` on a
///   Mac, and so on. So `application-android.properties` and
///   `@Profile(['ios'])` beans just work. The build is one too
///   ([buildModeProfile]): `release`, `profile` or `debug`, so
///   `application-release.yml` configures what users run.
/// - The OS environment is not read: on a phone it is noise, and values
///   come from `--dart-define` instead. A build that defines
///   `spring.flutter.scan-os-environment=true` reads it.
/// - A hot reload restarts the context when the generated code changed
///   (new or changed beans, annotations, `lib/resources/`), like Spring
///   Boot DevTools' restart, and builds the widgets below afresh. When only
///   method bodies changed, the context and the beans' state stay. After
///   such a restart the runners run again only with
///   [rerunRunnersOnReload]; `spring.devtools.restart.enabled=false` turns
///   the restarts off.
/// - A SQL database (`spring.datasource.url`, or `spring.datasources.<name>`)
///   on SQLite finds its file in the app's own directory, and its calls run
///   on an isolate of their own, not the UI's: the starter sets
///   `spring.datasource.sqlite.base-directory` to the directory of
///   `spring.datasource.sqlite.location` (`support`, the default, `cache`
///   or `documents`; on Android `databases/`) and
///   `spring.datasource.sqlite.isolate` to `true`, with the lowest
///   precedence: the app's own properties win. Nothing on the web.
/// - On macOS, Windows and Linux the native window is set up from
///   `spring.flutter.desktop.window.title-bar` (`default`, `transparent`,
///   `hidden`), `initial-size` and `min-size` (`1280x800`, logical
///   pixels) before the first frame is shown; `DesktopWindow` gives the
///   space the window buttons take to the widgets below, and
///   `WindowDragArea` moves the window. Nothing on phones and the web.
/// - Each change of the app's lifecycle is published as an
///   [AppLifecycleStateEvent]. In the background the context is paused
///   (`@Scheduled` tasks and WebSocket connections stop) and it restarts
///   when the app comes back, unless
///   `spring.flutter.lifecycle.pause-in-background=false`.
/// - the context is closed when this widget is removed.
///
/// Spring (Java) has no widget; the nearest is the `main` method of a
/// Spring Boot app, `SpringApplication.run(App.class, args)`.
class SpringApplicationWidget extends StatefulWidget {
  /// Runs the application [application] returns, then shows [home] in a
  /// [SpringApp], or shows [child], or, with neither, a [SpringApp] on the
  /// application's router. [home] and [child] are not given together.
  const SpringApplicationWidget({
    required this.application,
    this.child,
    this.home,
    this.splash,
    this.failure,
    this.args = const [],
    this.rerunRunnersOnReload = false,
    this.desktopWindowSetup,
    super.key,
  }) : assert(
         child == null || home == null,
         'SpringApplicationWidget takes a home or a child, not both',
       );

  /// Returns the application to run: `() => springApplication`, the
  /// variable the generator writes into `main.spring.dart`. It is a
  /// function, not the value, so that a hot reload can fetch the new
  /// generated code and restart the context with it.
  final SpringApplication Function() application;

  /// The app, shown once the application has started, for an app that
  /// builds its own app widget (`MaterialApp`, ...). Not together with
  /// [home].
  final Widget? child;

  /// The first page of a [SpringApp] built from the configuration, shown
  /// once the application has started. Not together with [child]; without
  /// both, the [SpringApp] uses the application's router.
  final Widget? home;

  /// Builds what is shown while the application starts, such as a logo.
  /// It wins over the theme's `splash`; without either an empty box is
  /// shown.
  final WidgetBuilder? splash;

  /// Builds what is shown when the start (or a restart after a hot reload)
  /// fails, from the error. By default a plain screen shows the error (in
  /// release builds only a short note). The failure is logged either way.
  final Widget Function(BuildContext context, Object error)? failure;

  /// Command-line arguments, read as properties (`--name=value`), for
  /// desktop apps started with some; none by default.
  final List<String> args;

  /// Whether `ApplicationRunner` / `CommandLineRunner` beans run again
  /// when a hot reload restarts the context, as with Spring Boot DevTools.
  /// `false` by default: the app did not really start again.
  final bool rerunRunnersOnReload;

  /// How the desktop window is set up from the properties; the plugin's
  /// by default. Only tests pass another.
  @visibleForTesting
  final DesktopWindowSetup? desktopWindowSetup;

  @override
  State<SpringApplicationWidget> createState() =>
      _SpringApplicationWidgetState();
}

class _SpringApplicationWidgetState extends State<SpringApplicationWidget> {
  ConfigurableApplicationContext? _context;
  Object? _error;
  late final AppLifecycleListener _lifecycle;
  bool _paused = false;
  Future<void> _lifecycleWork = Future.value();
  // Where the SQLite files can live; read once, before the first start.
  SqliteDirectories? _directories;
  // `spring.flutter.desktop.window.*`, applied while the start goes on.
  late final DesktopWindowSetup _windowSetup;
  DesktopWindowData _window = DesktopWindowData.none;
  bool _firstFrameHeld = false;
  // The start's progress for the theme's splash, 0 to 1.
  final _progress = ValueNotifier<double>(0);
  // The context being started, and the share of the loader its beans take:
  // the splash tasks take the rest, once it is known they exist.
  ConfigurableApplicationContext? _starting;
  double _beanSpan = 1;
  bool _beanSpanKnown = false;
  // The active theme once the properties are read, when it has a splash.
  SpringThemeData? _splashTheme;
  bool _splashDone = false;
  bool _handedOff = false;
  // The stages of the start, from the web page's (with their times).
  late final SplashStages _stages = SplashStages(reached: _pageStages());
  final _splashKey = GlobalKey();
  final _appKey = GlobalKey();

  @override
  void initState() {
    super.initState();
    if (widget.splash != null) {
      _handOffAfterFrame();
    }
    _windowSetup = widget.desktopWindowSetup ?? DesktopWindowSetup();
    _holdFirstFrame();
    _lifecycle = AppLifecycleListener(onStateChange: _onLifecycle);
    unawaited(_start());
  }

  // The runners show the window with the first frame, so holding it back
  // keeps the window hidden until the title bar and the size are set: no
  // flicker. Released as soon as the properties are applied (or none
  // are), and in any case when the start ends.
  void _holdFirstFrame() {
    if (!_windowSetup.isSupported) {
      return;
    }
    _firstFrameHeld = true;
    WidgetsBinding.instance.deferFirstFrame();
    unawaited(_windowSetup.ready.whenComplete(_releaseFirstFrame));
  }

  void _releaseFirstFrame() {
    if (_firstFrameHeld) {
      _firstFrameHeld = false;
      WidgetsBinding.instance.allowFirstFrame();
    }
  }

  // The stages the web page loader went through (none elsewhere).
  static Map<SplashStage, Duration> _pageStages() => {
    for (final MapEntry(:key, :value) in LoaderHandOff.pageStages().entries)
      ?SplashStage.values.where((s) => s.name == key).firstOrNull: value,
  };

  // Tells the web page loader the Flutter side is on screen; once.
  void _handOff() {
    if (!_handedOff) {
      _handedOff = true;
      _stages.enter(SplashStage.splash);
      LoaderHandOff.call(_progress.value);
    }
  }

  // The theme's splash painted. The web page loader stays over it until
  // the app is built under it too: the page's loader moves without the
  // engine, the splash stops while the app's first frames are made (the
  // page's own timeout removes it anyway).
  void _splashShown() {
    _stages.enter(SplashStage.splash);
    if (_context != null || _error != null) {
      _handOff();
    }
  }

  // The app's first frames are made: the splash takes over from the page
  // loader.
  void _handOffAfterAppFrames() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        _handOffAfterFrame();
      }
    });
    WidgetsBinding.instance.scheduleFrame();
  }

  // The context exists, its beans not yet: the start's stage, the
  // `splashStages` bean, the pacer and the trace of
  // `spring.flutter.splash.*`.
  void _contextInitialized(ApplicationContextInitializedEvent event) {
    // The listener stays on the application: a later run of the same
    // application by another widget is not this one's.
    if (!mounted || _context != null) {
      return;
    }
    final context = event.applicationContext;
    final environment = context.environment;
    final factory = context.beanFactory;
    factory.registerSingleton(
      'splashStages',
      _stages,
      types: const [SplashStages, ChangeNotifier, Listenable],
    );
    final yieldFrames =
        environment.getPropertyAs<bool>(
          'spring.flutter.splash.yield-frames',
        ) ??
        kIsWeb;
    if (factory is DefaultListableBeanFactory) {
      if (yieldFrames) {
        factory.startupPacer = FramePacer(
          budget:
              environment.getPropertyAs<Duration>(
                'spring.flutter.splash.frame-budget',
              ) ??
              const Duration(milliseconds: 8),
        );
      }
      // The stages and the events always; each bean with the trace or the
      // debug timeline.
      final trace =
          environment.getPropertyAs<bool>('spring.flutter.splash.trace') ??
          false;
      final startup = SplashTrace(
        _stages,
        beans:
            trace ||
            (environment.getPropertyAs<bool>(
                  'spring.flutter.debug.timeline.enabled',
                ) ??
                false),
        log: trace,
      );
      factory
        ..applicationStartup = startup
        ..registerSingleton('splashTrace', startup);
    }
    _starting = context;
    _beanSpan = 1 - SplashTasks.shareIn(environment);
    _stages.enter(SplashStage.starting);
  }

  // The beans' progress on the loader: their share of it, known for sure
  // once the definitions are frozen (no splash task: all of it).
  double _beansProgress(double fraction) {
    final starting = _starting;
    final factory = starting?.beanFactory;
    if (!_beanSpanKnown &&
        factory is DefaultListableBeanFactory &&
        factory.isConfigurationFrozen) {
      _beanSpanKnown = true;
      if (!SplashTasks.any(starting!)) {
        _beanSpan = 1;
      }
    }
    return fraction * _beanSpan;
  }

  // The splash tasks of [context], the loader going on from the beans'.
  Future<void> _runSplashTasks(ApplicationContext context) async {
    if (!SplashTasks.any(context)) {
      return;
    }
    _stages.enter(SplashStage.tasks);
    final from = _progress.value;
    await SplashTasks.of(context).run((fraction) {
      if (mounted) {
        _progress.value = math.max(
          _progress.value,
          from + (1 - from) * fraction,
        );
      }
    });
  }

  void _handOffAfterFrame() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        _handOff();
      }
    });
    WidgetsBinding.instance.scheduleFrame();
  }

  // The properties are read: the theme's splash can show from here on,
  // before any bean exists. A theme that cannot be read is reported by the
  // start itself; no splash shows then.
  void _environmentPrepared(ApplicationEnvironmentPreparedEvent event) {
    SpringThemeData? theme;
    try {
      final themes = SpringThemes.fromEnvironment(
        event.environment,
        addresses: event.springApplication.remoteAddresses,
      );
      theme = themes.data(_splashThemeName(themes));
    } on Object catch (error) {
      _log.debug(() => 'No theme splash: $error');
    }
    if (!mounted) {
      return;
    }
    if (theme?.splash == null) {
      _handOffAfterFrame();
      return;
    }
    setState(() => _splashTheme = theme);
  }

  // The theme `active` names, or by the device's brightness for `system`.
  static String _splashThemeName(SpringThemes themes) {
    final config = themes.config;
    final active = config.active.toLowerCase();
    if (active != 'system') {
      return themes.nameOf(config.active) ?? 'light';
    }
    final dark =
        WidgetsBinding.instance.platformDispatcher.platformBrightness ==
        Brightness.dark;
    return themes.nameOf(dark ? config.systemDark : config.systemLight) ??
        (dark ? 'dark' : 'light');
  }

  Future<void> _start() async {
    ConfigurableApplicationContext? started;
    try {
      // `asset:` resources: exists() needs the asset manifest.
      await AssetProtocolResolver.loadRootManifest();
      _directories ??= await SqliteDirectories.resolve();
      final application = widget.application();
      _directories?.provideTo(application);
      _windowSetup.provideTo(application);
      application.progressListener = (progress) {
        if (mounted) {
          _progress.value = math.max(
            _progress.value,
            _beansProgress(progress.fraction),
          );
        }
      };
      if (widget.splash == null) {
        application.addListener<ApplicationEnvironmentPreparedEvent>(
          _environmentPrepared,
        );
      }
      application.addListener<ApplicationContextInitializedEvent>(
        _contextInitialized,
      );
      final context = started = await application.runAsync(
        widget.args,
        systemEnvironment: _scanOsEnvironment(application) ? null : const {},
        additionalProfiles: [...platformProfiles(), buildModeProfile()],
      );
      SpringWidgetBindings.check(context);
      _checkApp(context);
      await _loadFonts(context);
      if (!mounted) {
        await context.closeAsync();
        return;
      }
      _window = await _windowSetup.settle();
      if (!mounted) {
        await context.closeAsync();
        return;
      }
      await _runSplashTasks(context);
      if (!mounted) {
        await context.closeAsync();
        return;
      }
      _stages
        ..enter(SplashStage.ready)
        ..publishTo(context);
      setState(() => _context = context);
      if (_splashTheme != null) {
        _handOffAfterAppFrames();
      } else {
        _handOffAfterFrame();
        _stages
          ..enter(SplashStage.exit)
          ..enter(SplashStage.app);
      }
    } catch (error) {
      // The application started, then a check of the widget failed: its
      // runners and scheduled tasks must not go on behind the failure
      // screen (and a hot reload's retry starts a new one).
      if (started != null) {
        await _closeQuietly(started);
      }
      if (mounted) {
        setState(() => _error = error);
        _handOffAfterFrame();
      }
    } finally {
      unawaited(_windowSetup.settle());
    }
  }

  static Future<void> _closeQuietly(
    ConfigurableApplicationContext context,
  ) async {
    if (!context.isActive) {
      return;
    }
    try {
      await context.closeAsync();
    } catch (error, stackTrace) {
      FlutterError.reportError(
        FlutterErrorDetails(
          exception: error,
          stack: stackTrace,
          library: 'spring_boot_starter_flutter',
          context: ErrorDescription(
            'while closing the application context after a failed start',
          ),
        ),
      );
    }
  }

  // An invalid `spring.flutter.app.*` value fails the start. The router
  // first: it reads the first address, whose language the app's settings
  // take (`FlutterAppSettings.locale`).
  void _checkApp(ApplicationContext context) {
    if (widget.child == null) {
      if (widget.home == null) {
        SpringApp.routerOf(context); // the router the app widget needs
      }
      FlutterAppSettings.of(context);
      ThemeSelection.of(context); // reads and checks every theme
    }
  }

  // The app's font files, before the first frame.
  Future<void> _loadFonts(ApplicationContext context) {
    final manifest = AssetProtocolResolver.rootManifest;
    if (manifest == null) {
      return Future.value();
    }
    final themes = SpringThemes.of(context);
    // The language the app starts in: the settings' (the navigation
    // starter: the first address's), else the device's.
    final locale = widget.child == null
        ? FlutterAppSettings.of(context).locale
        : null;
    return ThemeFonts.loadFor(
      context,
      rootBundle,
      manifest.listAssets(),
      themeFamilies: {
        for (final name in themes.names) ...themes.data(name).fontFamilies,
      },
      language: (locale ?? PlatformDispatcher.instance.locale).toLanguageTag(),
    );
  }

  static bool _scanOsEnvironment(SpringApplication application) {
    return scanOsEnvironmentIn(application.dartDefines);
  }

  @override
  void reassemble() {
    super.reassemble();
    final running = _context;
    if (running == null) {
      if (_error != null) {
        // The start failed: try again with the reloaded code.
        setState(() => _error = null);
        unawaited(_start());
      }
      return;
    }
    if (!_restartEnabled(running)) {
      return;
    }
    ConfigurableApplicationContext? restarted;
    try {
      final application = widget.application();
      _directories?.provideTo(application);
      _windowSetup.provideTo(application);
      final context = application.reload(
        running,
        runners: widget.rerunRunnersOnReload,
      );
      if (!identical(context, running)) {
        restarted = context;
        SpringWidgetBindings.check(context);
        _checkApp(context);
        _paused = false;
        // A changed window property is applied by the new context's
        // start; its answer replaces the data.
        unawaited(
          _windowSetup.settle().then((data) {
            if (mounted && data != _window) {
              setState(() => _window = data);
            }
          }),
        );
        setState(() => _context = context);
      }
    } catch (error) {
      // The new context started, then a check failed: it is closed, and
      // so is the old one (reload closes it first; not when the reload
      // failed before), so the next reload's retry (_start) runs the
      // only context.
      if (restarted != null) {
        unawaited(_closeQuietly(restarted));
      }
      if (running.isActive) {
        unawaited(_closeQuietly(running));
      }
      setState(() {
        _context = null;
        _error = error;
      });
    }
  }

  void _onLifecycle(AppLifecycleState state) {
    final context = _context;
    if (context == null || !context.isActive) {
      return;
    }
    context.publishEvent(AppLifecycleStateEvent(context, state));
    final pause =
        state == AppLifecycleState.hidden || state == AppLifecycleState.paused;
    if ((!pause && state != AppLifecycleState.resumed) ||
        pause == _paused ||
        !_pauseInBackground(context)) {
      return;
    }
    _paused = pause;
    _lifecycleWork = _lifecycleWork.then((_) async {
      if (!context.isActive) {
        return;
      }
      try {
        if (pause) {
          await context.pauseAsync();
        } else {
          context.restart();
        }
      } catch (error, stackTrace) {
        FlutterError.reportError(
          FlutterErrorDetails(
            exception: error,
            stack: stackTrace,
            library: 'spring_boot_starter_flutter',
            context: ErrorDescription(
              pause
                  ? 'while pausing the application context'
                  : 'while restarting the application context',
            ),
          ),
        );
      }
    });
  }

  // Spring Boot DevTools' switch for restarts after code changes.
  static bool _restartEnabled(ConfigurableApplicationContext context) =>
      boundProperties<FlutterRestartProperties>(
        context.environment,
        'flutterRestartProperties',
      ).enabled;

  static bool _pauseInBackground(ConfigurableApplicationContext context) =>
      boundProperties<FlutterLifecycleProperties>(
        context.environment,
        'flutterLifecycleProperties',
      ).pauseInBackground;

  @override
  void dispose() {
    _progress.dispose();
    _stages.dispose();
    _releaseFirstFrame();
    _lifecycle.dispose();
    final context = _context;
    _context = null;
    if (context != null && context.isActive) {
      unawaited(context.closeAsync());
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final error = _error;
    if (error != null) {
      return widget.failure?.call(context, error) ?? _Failure(error);
    }
    final running = _context;
    final themed = widget.splash == null ? _splashTheme : null;
    if (running == null) {
      if (themed != null && !_splashDone) {
        return _splashLayer(themed, ready: false);
      }
      return widget.splash?.call(context) ?? const SizedBox.shrink();
    }
    final app = SpringScope(
      applicationContext: running,
      // A new context starts the widgets afresh: none keeps a bean of the
      // closed one in its state.
      child: DesktopWindow(
        data: _window,
        child: KeyedSubtree(
          key: ObjectKey(running),
          child: widget.child ?? SpringApp(home: widget.home),
        ),
      ),
    );
    if (themed == null) {
      return app;
    }
    // The app is built under the splash, which fades out when it is
    // ready; the stack stays when it is gone, so the app keeps its state.
    return Stack(
      textDirection: TextDirection.ltr,
      fit: StackFit.expand,
      children: [
        KeyedSubtree(key: _appKey, child: app),
        if (!_splashDone) _splashLayer(themed, ready: true),
      ],
    );
  }

  // The theme's splash, with what it needs above the app widget: a text
  // direction and a media query.
  Widget _splashLayer(SpringThemeData theme, {required bool ready}) {
    return Directionality(
      key: _splashKey,
      textDirection: TextDirection.ltr,
      child: MediaQuery.fromView(
        view: View.of(context),
        child: ThemeSplash(
          theme: theme,
          progress: _progress,
          ready: ready,
          stages: _stages,
          onShown: _splashShown,
          onExiting: () => _stages.enter(SplashStage.exit),
          onExited: () {
            _stages.enter(SplashStage.app);
            if (mounted) {
              setState(() => _splashDone = true);
            }
          },
        ),
      ),
    );
  }
}

/// The default failure screen: the error in debug builds, a short note in
/// release builds (the details are in the log).
class _Failure extends StatelessWidget {
  const _Failure(this.error);

  final Object error;

