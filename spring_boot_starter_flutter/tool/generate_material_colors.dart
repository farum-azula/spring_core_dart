// Writes lib/src/theme/material_colors.dart: Flutter's `Colors` as a const
// table by name (`deepPurple`, `deepPurple.shade200`, `black54`), read
// from the SDK's colors.dart, so theme properties name colors without
// reflection. Run once, and again after a Flutter update adds colors:
//
//   dart run tool/generate_material_colors.dart [path/to/colors.dart]
import 'dart:io';

void main(List<String> args) {
  Directory.current = File.fromUri(Platform.script).parent.parent;
  final source = File(args.isNotEmpty ? args.first : _sdkColors());
  final text = source.readAsStringSync();

  final primaries = {
    for (final m in RegExp(
      r'static const int (_\w+(?:PrimaryValue|AccentValue)) = (0x[0-9A-Fa-f]{8});',
    ).allMatches(text))
      m[1]!: m[2]!,
  };
  final colors = <String, String>{};
  for (final m in RegExp(
    r'static const Color (\w+) = Color\((0x[0-9A-Fa-f]{8})\);',
  ).allMatches(text)) {
    colors[m[1]!] = m[2]!;
  }
  for (final m in RegExp(
    r'static const Material(?:Accent)?Color (\w+) = Material(?:Accent)?Color\(\s*(_\w+),\s*<int, Color>\{([^}]*)\}',
  ).allMatches(text)) {
    final name = m[1]!;
    colors[name] = primaries[m[2]!]!;
    for (final shade in RegExp(
      r'(\d+): Color\((0x[0-9A-Fa-f]{8}|_\w+)\)',
    ).allMatches(m[3]!)) {
      final value = shade[2]!;
      colors['$name.shade${shade[1]}'] = value.startsWith('_')
          ? primaries[value]!
          : value;
    }
  }
  if (colors.length < 200) {
    stderr.writeln('Only ${colors.length} colors found in ${source.path}.');
    exit(1);
  }

  final out = StringBuffer()
    ..writeln('// Generated by tool/generate_material_colors.dart from')
    ..writeln("// Flutter's Colors; do not edit.")
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln(
      "/// Flutter's `Colors` by name: `deepPurple`, `deepPurple.shade200`,",
    )
    ..writeln('/// `redAccent.shade100`, `black54`.')
    ..writeln('const materialColors = <String, Color>{');
  for (final MapEntry(:key, :value) in colors.entries) {
    out.writeln("  '$key': Color($value),");
  }
  out.writeln('};');
  File('lib/src/theme/material_colors.dart').writeAsStringSync(out.toString());
  stdout.writeln('${colors.length} colors written.');
}

String _sdkColors() {
  final flutter = Process.runSync('which', [
    'flutter',
  ]).stdout.toString().trim();
  final root = File(File(flutter).resolveSymbolicLinksSync()).parent.parent;
  return '${root.path}/packages/flutter/lib/src/material/colors.dart';
}
