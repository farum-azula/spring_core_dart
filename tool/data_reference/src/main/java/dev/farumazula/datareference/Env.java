package dev.farumazula.datareference;

import java.sql.SQLException;
import java.util.List;
import javax.sql.DataSource;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.PlatformTransactionManager;

/**
 * The world of the scenarios: the data source of a database of their own, a
 * template, the transaction manager, and the helpers that turn what happens
 * into the normalized outcome (the Dart suite,
 * spring_boot_starter_data/test/transaction_matrix, writes the same).
 *
 * <p>Values of an outcome are numbers, strings and lists of them. An error
 * becomes the string {@code !ClassName[SQLSTATE]} (the state when a driver
 * error is behind it).
 */
@Component
public class Env {
    static final String[] SCHEMA = {
        "create table if not exists wallets (id bigint primary key, owner text not null, balance bigint not null)",
        "create table if not exists doctors (name text primary key, on_call boolean not null)",
        "create table if not exists counters (id bigint primary key, value bigint not null)",
        "create table if not exists log (id bigint generated always as identity primary key, who text not null)",
        "create table if not exists accounts (iban text primary key, owner text not null, version bigint not null)",
        "create table if not exists stock (id bigint generated by default as identity primary key, sku text not null, quantity bigint not null)",
    };

    static final String[] SEED = {
        "truncate wallets, doctors, counters, log, accounts, stock",
        "insert into wallets values (1, 'ada', 100), (2, 'bob', 50)",
        "insert into doctors values ('alice', true), ('bob', true)",
        "insert into counters values (1, 0)",
        "insert into stock (id, sku, quantity) values (1, 'a', 5), (2, 'b', 1), (3, 'c', 9)",
        "insert into accounts values ('acc-1', 'ada', 1)",
    };

    final DataSource dataSource;
    final JdbcTemplate jdbc;
    final PlatformTransactionManager manager;

    Env(DataSource dataSource, JdbcTemplate jdbc, PlatformTransactionManager manager) {
        this.dataSource = dataSource;
        this.jdbc = jdbc;
        this.manager = manager;
    }

    void createSchema() {
        for (String statement : SCHEMA) {
            jdbc.execute(statement);
        }
    }

    /** Puts the tables back to the seed. */
    void reset() {
        for (String statement : SEED) {
            jdbc.execute(statement);
        }
    }

    /** A template whose statements stop after {@code seconds}. */
    JdbcTemplate jdbcWithTimeout(int seconds) {
        JdbcTemplate template = new JdbcTemplate(dataSource);
        template.setQueryTimeout(seconds);
        return template;
    }

    long scalar(String sql) {
        Long value = jdbc.queryForObject(sql, Long.class);
        return value == null ? -1 : value;
    }

    String text(String sql) {
        return jdbc.queryForObject(sql, String.class);
    }

    /** The {@code who} of the log, sorted: what the transactions committed. */
    List<String> logRows() {
        return jdbc.queryForList("select who from log order by who", String.class);
    }

    /** The id of the running transaction, or {@code none} outside one. */
    String txState() {
        long first = scalar("select txid_current()");
        long second = scalar("select txid_current()");
        return first == second ? Long.toString(first) : "none";
    }

    /**
     * Waits until at least {@code count} backends wait for a lock in this
     * database; false when nobody does within five seconds.
     */
    boolean awaitBlocked(int count) {
        long deadline = System.nanoTime() + 5_000_000_000L;
        while (true) {
            long blocked = scalar("select count(*) from pg_stat_activity "
                    + "where datname = current_database() and wait_event_type = 'Lock'");
            if (blocked >= count) {
                return true;
            }
            if (System.nanoTime() > deadline) {
                return false;
            }
            try {
                Thread.sleep(10);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                return false;
            }
        }
    }

    boolean awaitBlocked() {
        return awaitBlocked(1);
    }

    /** The error of a scenario as its outcome string. */
    static String kindOf(Throwable error) {
        String name = error.getClass().getSimpleName();
        String state = sqlState(error);
        return state == null ? name : name + "[" + state + "]";
    }

    private static String sqlState(Throwable error) {
        int depth = 0;
        for (Throwable e = error; e != null && depth < 8; e = e.getCause(), depth++) {
            if (e instanceof SQLException sql) {
                return sql.getSQLState();
            }
        }
        return null;
    }

    /** What the action gives, or its error as {@code !Kind}. */
    static Object attempt(Action action) {
        try {
            return action.run();
        } catch (Throwable error) {
            return "!" + kindOf(error);
        }
    }

    interface Action {
        Object run() throws Throwable;
    }

    interface Body {
        void run() throws Throwable;
    }

    /** {@code ok}, or the error of the body as {@code !Kind}. */
    static String completion(Body body) {
        try {
            body.run();
            return "ok";
        } catch (Throwable error) {
            return "!" + kindOf(error);
        }
    }
}
