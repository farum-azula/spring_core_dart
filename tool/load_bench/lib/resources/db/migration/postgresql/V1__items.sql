-- The table of the database scenarios on PostgreSQL, with 1000 rows to
-- read (GET /db/items/{id}); POST /db/items adds rows after them.
create table items (
  id integer generated by default as identity (start with 1001) primary key,
  name text not null,
  price double precision not null,
  quantity integer not null
);

insert into items (id, name, price, quantity)
select n, 'item ' || n, n * 1.5, n % 100 from generate_series(1, 1000) as n;
