// Runtime types are always imported from the public library, never from
// `src/`.
const _springUrl = 'package:spring_core_dart/spring_core_dart.dart';

const _payloadApplicationEvent = TypeChecker.typeNamedLiterally(
  'PayloadApplicationEvent',
  inPackage: 'spring_core_dart',
);

// A reference to a public runtime type, e.g. `BeanDefinition`.
Reference _spring(String name) => refer(name, _springUrl);

/// String literal that keeps `$` and backslashes intact.
Expression _str(String value) => literalString(value, raw: true);

/// Turns a [ModuleModel] into the source of a `*.spring.dart` library.
///
/// The emitted library contains, in this order: one `_$...Proxy` class per
/// proxied bean and a single `final BeanModule $<name>` variable with a
/// `BeanDefinition` per bean plus the module's property sources,
/// introspections and configurers. Code is built with `code_builder` (so
/// imports get prefixes such as `_i1.`; omitted in the examples below) and
/// formatted with `dart_style`.
///
/// ```dart
/// // Input:
/// @Service()
/// class Greeter {
///   Greeter(this.clock);
///   final Clock clock;
/// }
/// // Output (beans.spring.dart, ProxyMode.none):
/// // GENERATED CODE - DO NOT MODIFY BY HAND
/// // Generated by spring_core_dart_generator from @ComponentScan.
///
/// /// Beans found by `@ComponentScan` in `lib/src/`.
/// final BeanModule $appBeans = BeanModule(r'appBeans', [
///   BeanDefinition<Greeter>(
///     name: r'greeter',
///     source: r'package:app/src/greeter.dart#Greeter',
///     types: const [Greeter],
///     dependencies: const [Dependency(Clock, name: r'clock')],
///     create: (r) => Greeter(r.dependency<Clock>(name: r'clock')),
///   ),
/// ]);
/// ```
///
/// Spring (Java):
///
/// ```java
/// // Classic Spring keeps definitions in memory and uses reflection to
/// // create beans. Spring 6 AOT is the closest match: during the build a
/// // BeanFactoryInitializationAotProcessor (BeanRegistrationsAotContribution)
/// // writes Java source that registers the beans without reflection:
/// public static BeanDefinition getGreeterBeanDefinition() {
///   RootBeanDefinition definition = new RootBeanDefinition(Greeter.class);
///   definition.setInstanceSupplier(BeanInstanceSupplier
///       .<Greeter>forConstructor(Clock.class)
///       .withGenerator((registeredBean, args) ->
///           new Greeter(args.get(0))));
///   return definition;
/// }
/// ```
class ModuleEmitter {
  /// Creates an emitter for the library [output] (used to compute
  /// relative imports).
  ///
  /// ```dart
  /// final emitter = ModuleEmitter(input.changeExtension('.spring.dart'));
  /// ```
  ModuleEmitter(
    this.output, {
    this.dependencies,
    this.pruneProxies = true,
    this.foreignAdvice,
  });

  /// The aspects and advisors of the application's other modules, when
  /// they are all known (the `@SpringBootApplication` output); without
  /// them no proxy is pruned (see [analyzeAop]).
  final ForeignAdvice? foreignAdvice;

  /// Whether `aop_proxies: all` skips the proxy classes of beans no
  /// pointcut of the application can match (build option `aop_prune`;
  /// only with [foreignAdvice]).
  final bool pruneProxies;

  // The module being emitted.
  late ModuleModel _module;

  /// The library being generated; used to make `asset:` imports relative.
  final AssetId output;

  /// The packages the generated library's package depends on directly
  /// (with itself); `null` when unknown. A declaration of any other
  /// package is imported through a library of these that exports it (the
  /// user's code reaches it that way), so the output does not trigger
  /// `depend_on_referenced_packages`.
  final Set<String>? dependencies;

  /// Returns the formatted source of the generated library.
  ///
  /// [moduleName] is the `BeanModule` name (the `@ComponentScan` variable),
  /// [variableName] the generated variable (`$` + [moduleName]),
  /// [scannedDirectory] is only used in the variable's doc comment.
  /// Throws `InvalidGenerationSource` when a type, constant or function
  /// cannot be referenced from [output] (e.g. private constants or files
  /// of another package outside `lib/`).
  ///
  /// ```dart
  /// final source = ModuleEmitter(output).emit(
  ///   moduleName: 'appBeans',
  ///   variableName: r'$appBeans',
  ///   scannedDirectory: 'lib/src',
  ///   module: module,
  /// );
  /// // source: "// GENERATED CODE ...
  /// //          final BeanModule $appBeans = BeanModule(r'appBeans', [...]);"
  /// ```
  ///
  /// Spring (Java):
  ///
  /// ```java
  /// // Spring 6 AOT writes the equivalent Java source (with JavaPoet) at
  /// // build time, e.g. AppConfig__BeanDefinitions.java and
  /// // AppConfig__BeanFactoryRegistrations.java.
  /// ```
  String emit({
    required String moduleName,
    required String variableName,
    required String scannedDirectory,
    required ModuleModel module,
    List<Spec> extra = const [],
    Map<String, ({String? text, String? base64})> resources = const {},
  }) {
    _module = module;
    _usesTypeOf = false;
    analyzeAop(module, prune: pruneProxies, foreign: foreignAdvice);
    final arguments = <String, Expression>{
      if (module.imports.isNotEmpty)
        'imports': literalList([
          for (final variable in module.imports)
            refer(
              variable.name!,
              _importUrl(variable.library.uri, variable, name: variable.name),
            ),
        ]),
      if (resources.isNotEmpty)
        'resources': literalConstMap({
          for (final MapEntry(key: path, value: (:text, :base64))
              in resources.entries)
            _str(path): text != null
                ? _spring('EmbeddedResource')
                      .constInstanceNamed('text', [_str(text)])
                : _spring('EmbeddedResource')
                      .constInstanceNamed('base64', [_str(base64!)]),
        }),
      if (module.propertySources.isNotEmpty)
        'propertySources': literalList([
          for (final source in module.propertySources) _propertySource(source),
        ]),
      if (module.registrars.isNotEmpty)
        'registrars': literalList([
          for (final registrar in module.registrars)
            _spring('ImportDeclaration').newInstance(
              [_type(registrar.type, registrar.element).property('new')],
              {
                if (registrar.conditions.isNotEmpty)
                  'conditions': literalList([
                    for (final condition in registrar.conditions)
                      _condition(condition, registrar.element),
                  ]),
              },
            ),
        ]),
      if (module.introspections.isNotEmpty)
        'introspections': literalList([
          for (final introspection in module.introspections)
            _introspection(introspection),
        ]),
      if (module.configurables.isNotEmpty)
        'configurers': literalMap({
          for (final configurable in module.configurables)
            _type(configurable.type, configurable.element): _configurer(
              configurable,
            ),
        }),
      if (module.configurables.any((c) => c.postConstruct.isNotEmpty))
        'configurablePostConstruct': literalMap({
          for (final configurable in module.configurables)
            if (configurable.postConstruct.isNotEmpty)
              _type(configurable.type, configurable.element):
                  _configurableCalls(configurable, configurable.postConstruct),
        }),
      if (module.configurables.any((c) => c.preDestroy.isNotEmpty))
        'configurablePreDestroy': literalMap({
          for (final configurable in module.configurables)
            if (configurable.preDestroy.isNotEmpty)
              _type(configurable.type, configurable.element):
                  _configurableCalls(configurable, configurable.preDestroy),
        }),
    };
    final moduleExpression = _spring('BeanModule').newInstance([
      _str(moduleName),
      literalList([for (final bean in module.beans) _definition(bean)]),
    ], arguments);
    final library = Library(
      (b) => b
        ..body.addAll([
          for (final bean in module.beans)
            if (bean.proxy case final proxy?
                when proxy.unavailableReason == null)
              _proxyClass(proxy, bean.element, lookup: _lookupOf(bean)),
          for (final proxy in module.lazyProxies.values) _lazyClass(proxy),
          for (final bean in module.beans)
            if (bean.creation case InterfaceProxyCreation(:final model))
              _interfaceImplClass(model),
          for (final bean in module.beans)
            if (bean.creation case ConstructorCreation(
              configuration: final model?,
            ))
              configurationClass(model),
          for (final bean in module.beans)
            if (_lookupOf(bean) case final model?) lookupClass(model),
          if (module.beans.any(
            (bean) => switch (bean.creation) {
              ConstructorCreation(:final configuration?) =>
                configuration.beanMethods.any((m) => m.defaults.isNotEmpty),
              _ => false,
            },
          ))
            absentMarkerClass(),
        ])
        ..body.addAll([
          if (_usesTypeOf)
            Method(
              (m) => m
                ..docs.add(
                  '/// [T] as a `Type` value (function and record types).',
                )
                ..returns = refer('Type')
                ..name = typeOfFunction
                ..types.add(refer('T'))
                ..lambda = true
                ..body = refer('T').code,
            ),
        ])
        // A getter, not a final variable: a hot reload replaces its body,
        // so the next call returns the beans of the new code.
        ..body.add(
          Method(
            (m) => m
              ..docs.add(
                '/// Beans found by `@ComponentScan` in `$scannedDirectory`.',
              )
              ..type = MethodType.getter
              ..returns = _spring('BeanModule')
              ..name = variableName
              ..lambda = true
              ..body = moduleExpression.code,
          ),
        )
        ..body.addAll(extra),
    );
    final emitter = DartEmitter(
      allocator: Allocator.simplePrefixing(),
      orderDirectives: true,
      useNullSafetySyntax: true,
    );
    final source =
        '// GENERATED CODE - DO NOT MODIFY BY HAND\n'
        '// Generated by spring_core_dart_generator from @ComponentScan.\n\n'
        '// ignore_for_file: type=lint, implementation_imports, unnecessary_cast\n'
        // Proxies and bean definitions call members of the user's classes
        // whatever their package:meta / @Deprecated markers say.
        '// ignore_for_file: deprecated_member_use, '
        'invalid_use_of_visible_for_testing_member\n'
        '// ignore_for_file: invalid_use_of_internal_member, '
        'invalid_use_of_protected_member\n\n'
        '${library.accept(emitter)}';
    return DartFormatter(languageVersion: DartFormatter.latestLanguageVersion)
        .format(source);
  }

  // One `BeanDefinition<T>(...)`. Optional arguments are only written when
  // they differ from the runtime defaults, keeping the output small.
  Expression _definition(BeanModel bean) {
    final element = bean.element;
    final dependencies = bean.dependencies;
    final injection = _injection(bean.properties, bean.methods, element);
    return _spring('BeanDefinition').newInstance(
      [],
      {
        'name': _str(bean.name),
        'source': _str(bean.source),
        'types': bean.valueType != null
            ? _typeValues([bean.valueType!, ...bean.exposedTypes], element)
            : literalConstList([
                for (final type in bean.exposedTypes) _type(type, element),
              ]),
        if (bean.factoryObjectTypes case final products?)
          'factoryObjectTypes': literalConstList([
            for (final type in products) _type(type, element),
          ]),
        if (bean.aliases.isNotEmpty)
          'aliases': literalConstList([for (final a in bean.aliases) _str(a)]),
        if (bean.scope != 'singleton') 'scope': _str(bean.scope),
        if (bean.scopedProxy case final proxy?)
          'scopedProxy': refer(proxy.className).property('new'),
        if (bean.lazy) 'lazy': literalTrue,
        if (bean.primary) 'primary': literalTrue,
        if (bean.fallback) 'fallback': literalTrue,
        if (!bean.autowireCandidate) 'autowireCandidate': literalFalse,
        if (!bean.defaultCandidate) 'defaultCandidate': literalFalse,
        if (bean.creation case BeanMethodCreation(
          :final ownerName,
          :final methodName,
          :final isStatic,
        )) ...{
          if (!isStatic) 'factoryBeanName': _str(ownerName),
          'factoryMethodName': _str(methodName),
        },
        if (bean.order case final order?) 'order': literalNum(order),
        if (bean.description case final description?)
          'description': _str(description),
        if (bean.dependsOn.isNotEmpty)
          'dependsOn': literalConstList([
            for (final d in bean.dependsOn) _str(d),
          ]),
        if (bean.qualifiers.isNotEmpty)
          'qualifiers': literalConstSet({
            for (final q in bean.qualifiers) _str(q),
          }),
        if (bean.conditions.isNotEmpty)
          'conditions': literalList([
            for (final condition in bean.conditions)
              _condition(condition, element),
          ]),
        if (dependencies.isNotEmpty)
          'dependencies':
              dependencies.every(
                (p) => p.exactType == null || _isConstTypeValue(p.exactType!),
              )
              ? literalConstList([
                  for (final point in dependencies) _dependency(point, element),
                ])
              : literalList([
                  for (final point in dependencies) _dependency(point, element),
                ]),
        'create': _closure(['r'], _creation(bean).code, lambda: true),
        'inject': ?injection,
        if (bean.postConstruct.isNotEmpty)
          'postConstruct': _calls(bean.postConstruct, bean),
        if (bean.initMethod case final method?) ...{
          'initMethod': _calls([method], bean),
          'initMethodName': _str(method),
        },
        if (bean.preDestroy.isNotEmpty)
          'preDestroy': _calls(bean.preDestroy, bean),
        if (bean.destroyMethod case final method?) ...{
          'destroyMethod': _calls([method], bean),
          'destroyMethodName': _str(
            bean.destroyMethodInferred ? '(inferred)' : method,
          ),
        },
        if (bean.listeners.isNotEmpty)
          'eventListeners': literalList([
            for (final listener in bean.listeners)
              _listener(bean.type, listener, element),
          ]),
        if (bean.annotatedMethods.isNotEmpty)
          'annotatedMethods': literalList([
            for (final method in bean.annotatedMethods)
              _annotatedMethod(bean.type, method, element),
          ]),
        if (bean.annotations.isNotEmpty)
          'annotations': literalConstList([
            for (final annotation in bean.annotations)
              _constant(annotation, element),
          ]),
        if (bean.proxy case final proxy?)
          'aopProxy': _proxyFactory(proxy, element),
        if (bean.aspect case final aspect?)
          'aspect': _aspect(bean.type, aspect, element),
      },
      [
        if (bean.valueType case final valueType?)
          _anyType(valueType, element)
        else
          _type(bean.type, element),
      ],
    );
  }

  // A function or record type as a `Type` value: its public alias (a
  // constant), else `_$typeOf<T>()` (no literal exists for such types).
  Expression _typeValue(DartType type, Element element) {
    if (type is InterfaceType) {
      return _type(type, element);
    }
    final alias = type.alias;
    if (alias != null &&
        alias.element.isPublic &&
        alias.typeArguments.isEmpty &&
        type.nullabilitySuffix == NullabilitySuffix.none) {
      final name = alias.element.name!;
      return refer(
        name,
        _importUrl(alias.element.library.uri, element, name: name),
      );
    }
    _usesTypeOf = true;
    return refer(typeOfFunction).call([], {}, [_anyType(type, element)]);
  }

  bool _isConstTypeValue(DartType type) =>
      type is InterfaceType ||
      (type.alias?.element.isPublic ?? false) &&
          type.alias!.typeArguments.isEmpty &&
          type.nullabilitySuffix == NullabilitySuffix.none;

  // A `types:` list starting with a function or record type.
  Expression _typeValues(List<DartType> types, Element element) {
    final values = [for (final type in types) _typeValue(type, element)];
    return types.every(_isConstTypeValue)
        ? literalConstList(values)
        : literalList(values);
  }

  // Whether `_$typeOf` is used by the module being emitted.
  bool _usesTypeOf = false;

  /// The generated `Type _$typeOf<T>() => T;`.
  static const typeOfFunction = r'_$typeOf';

  // `inject: (bean, r) { bean.x = ...; bean.m(...); }`, or `null` when the
  // bean has no field, setter or method injection.
  Expression? _injection(
    List<PropertyInjection> properties,
    List<MethodInjection> methods,
    Element element,
  ) {
    if (properties.isEmpty && methods.isEmpty) {
      return null;
    }
    return _closure([
      'bean',
      'r',
    ], _injectionBody(refer('bean'), properties, methods, element));
  }

  // Members in Spring's order (superclass first; per class fields, then
  // setters and methods), see `injectionRank`.
  Code _injectionBody(
    Expression bean,
    List<PropertyInjection> properties,
    List<MethodInjection> methods,
    Element element,
  ) => Block.of([
    for (final (_, statement) in sortedByRank([
      for (final property in properties)
        (property.rank, _propertyStatement(bean, property, element)),
      for (final method in methods)
        (method.rank, _methodStatement(bean, method, element)),
    ], (entry) => entry.$1))
      statement,
  ]);

  Code _propertyStatement(
    Expression bean,
    PropertyInjection property,
    Element element,
  ) =>
      // An optional field or setter is left alone when nothing is found
      // (keeps its initializer; Spring does not call the setter either).
      property.point.optional && property.point.defaultValue == null
      ? Block.of([
          const Code('if ('),
          _lookup(property.point, element).code,
          const Code(' case final value?) {'),
          bean.property(property.name).assign(refer('value')).statement,
          const Code('}'),
        ])
      : bean
            .property(property.name)
            .assign(_lookup(property.point, element))
            .statement;

  Code _methodStatement(
    Expression bean,
    MethodInjection method,
    Element element,
  ) {
    final (positional, named) = _arguments(method.arguments, element);
    return bean.property(method.name).call(positional, named).statement;
  }

  // `(bean) { final target = bean as T; target.a(); }` for lifecycle
  // methods of a `@Configurable` class.
  Expression _configurableCalls(
    ConfigurableModel configurable,
    List<String> methods,
  ) => _closure(
    ['bean'],
    Block.of([
      declareFinal('target')
          .assign(
            refer('bean').asA(_type(configurable.type, configurable.element)),
          )
          .statement,
      for (final method in methods)
        refer('target').property(method).call([]).statement,
    ]),
  );

  // Configurers receive `Object`, hence the cast to the configurable type.
  Expression _configurer(ConfigurableModel configurable) {
    final element = configurable.element;
    return _closure(
      ['bean', 'r'],
      Block.of([
        declareFinal('target')
            .assign(refer('bean').asA(_type(configurable.type, element)))
            .statement,
        _injectionBody(
          refer('target'),
          configurable.properties,
          configurable.methods,
          element,
        ),
      ]),
    );
  }

  // Type parameters of the generic introspected class being written:
  // erased to their bound or `dynamic` (the raw introspection), or bound to
  // the type argument at this index of `specialize`'s `arguments`.
  Map<TypeParameterElement, DartType?> _erased = const {};
  Map<TypeParameterElement, int> _captured = const {};

  // The bound an erased type parameter stands for; `null` for `dynamic`
  // (also inside its own bound: `T extends Comparable<T>`).
  T _withoutErasure<T>(TypeParameterElement parameter, T Function() body) {
    final bound = _erased[parameter];
    _erased = {..._erased, parameter: null};
    try {
      return body();
    } finally {
      _erased = {..._erased, parameter: bound};
    }
  }

  // `BeanIntrospection<T>` with typed getter/setter closures and
  // `Function.apply` for methods: reflection-like access without mirrors.
  //
  // A generic class `Page<T>` is written with `T` erased
  // (`BeanIntrospection<Page<dynamic>>`), plus, when its type parameters
  // have no bounds, `specialize`: the introspection of `Page<X>` for the
  // `TypeInfo`s of the type arguments, captured as type parameters:
  //
  // ```dart
  // specialize: (arguments) => arguments[0].capture(
  //     <T>() => BeanIntrospection<Page<T>>(...,
  //         typeInfo: ListType<T>(arguments[0] as TypeInfo<T>))),
  // ```
  Expression _introspection(IntrospectionModel model) {
    final parameters = model.type.element.typeParameters;
    if (parameters.isEmpty) {
      return _introspectionOf(model);
    }
    Expression? specialize;
    if (parameters.every((p) => p.bound == null)) {
      _captured = {
        for (var i = 0; i < parameters.length; i++) parameters[i]: i,
      };
      var body = _introspectionOf(model);
      _captured = const {};
      for (var i = parameters.length - 1; i >= 0; i--) {
        // A generic function literal (`Method.closure` drops type
        // parameters).
        final captured = CodeExpression(
          Block.of([Code('<${parameters[i].name}>() => '), body.code]),
        );
        body = refer('arguments')
            .index(literalNum(i))
            .property('capture')
            .call([captured]);
      }
      specialize = _closure(['arguments'], body.code, lambda: true);
    }
    _erased = {for (final parameter in parameters) parameter: parameter.bound};
    final raw = _introspectionOf(model, specialize: specialize);
    _erased = const {};
    return raw;
  }

  // A generic class is created by calling its constructor, not with
  // `Function.apply(Page<T>.new, ...)`: dart2js cannot apply named
  // arguments to an instantiated tear-off. Absent optional parameters get
  // their default values, so all of them must be re-creatable.
  //
  // ```dart
  // create: (positional, named) => Page<T>((positional[0] as List<T>),
  //     total: named.containsKey(#total) ? (named[#total] as int) : 0),
  // ```
  Expression? _directCall(
    IntrospectionModel model,
    ConstructorModel constructor,
    TypeReference beanType,
  ) {
    if (model.type.element.typeParameters.isEmpty ||
        constructor.parameters.any(
          (p) => p.hasDefault && p.defaultValue == null,
        )) {
      return null;
    }
    final element = model.element;
    final positional = <Expression>[];
    final named = <String, Expression>{};
    for (final parameter in constructor.parameters) {
      final type = _anyType(parameter.type, element);
      final fallback = parameter.defaultValue == null
          ? literalNull
          : _constant(parameter.defaultValue!, element);
      if (parameter.isNamed) {
        final key = CodeExpression(Code('#${parameter.name}'));
        final value = refer('named').index(key).asA(type);
        named[parameter.name] = parameter.isRequired
            ? value
            : refer('named')
                  .property('containsKey')
                  .call([key])
                  .conditional(value, fallback);
      } else {
        final index = literalNum(positional.length);
        final value = refer('positional').index(index).asA(type);
        positional.add(
          parameter.isRequired
              ? value
              : refer('positional')
                    .property('length')
                    .greaterThan(index)
                    .conditional(value, fallback),
        );
      }
    }
    return constructor.name.isEmpty
        ? beanType.newInstance(positional, named)
        : beanType.newInstanceNamed(constructor.name, positional, named);
  }

  Expression _introspectionOf(
    IntrospectionModel model, {
    Expression? specialize,
  }) {
    final element = model.element;
    final beanType = _type(model.type, element);
    return _spring('BeanIntrospection').newInstance(
      [],
      {
        'className': _str(model.element.name!),
        'specialize': ?specialize,
        'properties': literalList([
          for (final property in model.properties)
            _spring('BeanProperty').newInstance(
              [_str(property.name)],
              {
                'type': _anyType(property.type, element),
                if (property.nullable) 'nullable': literalTrue,
                'typeInfo': _typeInfo(property.declaredType, element).$1,
                'get': _closure(
                  ['bean'],
                  refer('bean').property(property.name).code,
                  lambda: true,
                ),
                if (property.writable)
                  'set': _closure(
                    ['bean', 'value'],
                    refer('bean')
                        .property(property.name)
                        .assign(
                          refer('value').asA(
                            property.declaredType is TypeParameterType
                                ? _anyType(property.declaredType, element)
                                : _type(property.type, element).rebuild(
                                    (t) => t..isNullable = property.nullable,
                                  ),
                          ),
                        )
                        .code,
                    lambda: true,
                  ),
                if (property.annotations.isNotEmpty)
                  'annotations': literalConstList([
                    for (final annotation in property.annotations)
                      _constant(annotation, element),
                  ]),
              },
              [beanType],
            ),
        ]),
        if (model.methods.isNotEmpty)
          'methods': literalList([
            for (final method in model.methods)
              _spring('BeanMethod').newInstance(
                [_str(method.name)],
                {
                  if (method.returnType case final returnType?)
                    'returnType': _type(returnType, element),
                  if (method.parameterTypes.isNotEmpty)
                    // Not const when a type uses a captured type parameter.
                    'parameterTypes':
                        (_captured.isEmpty ? literalConstList : literalList)([
                          for (final t in method.parameterTypes)
                            _type(t, element),
                        ]),
                  'invoke': _closure(
                    ['bean', 'arguments'],
                    refer('Function').property('apply').call([
                      refer('bean').property(method.name),
                      refer('arguments'),
                    ]).code,
                    lambda: true,
                  ),
                  if (method.annotations.isNotEmpty)
                    'annotations': literalConstList([
                      for (final annotation in method.annotations)
                        _constant(annotation, element),
                    ]),
                },
                [beanType],
              ),
          ]),
        if (model.annotations.isNotEmpty)
          'annotations': literalConstList([
            for (final annotation in model.annotations)
              _constant(annotation, element),
          ]),
        if (model.instantiable)
          'instantiate': _closure(
            [],
            beanType.newInstance([]).code,
            lambda: true,
          ),
        if (model.constructor case final constructor?)
          'constructor': _spring('BeanConstructor').newInstance(
            [],
            {
              'parameters': literalList([
                for (final parameter in constructor.parameters)
                  _spring('BeanParameter').newInstance(
                    [_str(parameter.name)],
                    {
                      'type': _typeInfo(parameter.type, element).$1,
                      if (parameter.isNamed)
                        'symbol': CodeExpression(Code('#${parameter.name}')),
                      if (parameter.isRequired) 'isRequired': literalTrue,
                      if (parameter.annotations.isNotEmpty)
                        'annotations': literalConstList([
                          for (final annotation in parameter.annotations)
                            _constant(annotation, element),
                        ]),
                    },
                  ),
              ]),
              'create': _closure(
                ['positional', 'named'],
                (_directCall(model, constructor, beanType) ??
                        refer('Function')
                            .property('apply')
                            .call([
                              beanType.property(
                                constructor.name.isEmpty
                                    ? 'new'
                                    : constructor.name,
                              ),
                              refer('positional'),
                              refer('named'),
                            ])
                            .asA(beanType))
                    .code,
                lambda: true,
              ),
            },
            [beanType],
          ),
        if (model.fromJson case final fromJson?)
          'fromJson': _closure(
            ['json'],
            beanType.property('fromJson').call([
              refer('json').asA(_anyType(fromJson.parameterType, element)),
            ]).code,
            lambda: true,
          ),
        if (model.hasToJson)
          'toJson': _closure(
            ['bean'],
            refer('bean').property('toJson').call([]).code,
            lambda: true,
          ),
      },
      [beanType],
    );
  }

  // `TypeInfo` of a declared type: `ClassType<T>`, `ListType<E>(...)`,
  // `SetType`, `MapType`, `EnumType<E>(E.values)` or `DynamicType`;
  // `$2` says whether the expression is const (an enum with `@JsonValue`
  // needs a closure).
  (Expression, bool) _typeInfo(DartType type, Element element) {
    final nullable = type.nullabilitySuffix == NullabilitySuffix.question;
    // A captured type parameter of a specialized generic introspection:
    // the TypeInfo of its type argument.
    final erasedTo = type is TypeParameterType ? _erased[type.element] : null;
    if (type is TypeParameterType && erasedTo != null) {
      return _withoutErasure(type.element, () => _typeInfo(erasedTo, element));
    }
    final captured = type is TypeParameterType ? _captured[type.element] : null;
    if (type is TypeParameterType && captured != null) {
      // `asA` writes `(arguments[0] as TypeInfo<T>)`.
      final info = refer('arguments')
          .index(literalNum(captured))
          .asA(
            TypeReference(
              (t) => t
                ..symbol = 'TypeInfo'
                ..url = _springUrl
                ..types.add(refer(type.element.name!)),
            ),
          );
      return (nullable ? info.property('asNullable').call([]) : info, false);
    }
    final named = <String, Expression>{if (nullable) 'nullable': literalTrue};
    (Expression, bool) kind(
      String name,
      List<DartType> arguments,
      Map<String, Expression> extra,
    ) {
      final infos = [for (final a in arguments) _typeInfo(a, element)];
      final isConst = infos.every((info) => info.$2);
      final typeArguments = [
        for (final argument in arguments)
          _isDynamicInfo(argument)
              ? refer('dynamic')
              : _anyType(argument, element),
      ];
      final positional = [for (final info in infos) info.$1];
      return (
        isConst
            ? _spring(
                name,
              ).constInstance(positional, {...named, ...extra}, typeArguments)
            : _spring(name)
                  .newInstance(positional, {...named, ...extra}, typeArguments),
        isConst,
      );
    }

    if (type is InterfaceType && !_isDynamicInfo(type)) {
      final arguments = type.typeArguments;
      if ((type.isDartCoreList || type.isDartCoreIterable) &&
          arguments.length == 1) {
        return kind('ListType', arguments, const {});
      }
      if (type.isDartCoreSet && arguments.length == 1) {
        return kind('SetType', arguments, const {});
      }
      if (type.isDartCoreMap && arguments.length == 2) {
        return kind('MapType', arguments, const {});
      }
      // Other generic classes (`ResponseEntity<Book>`): the whole type plus
      // the description of each type argument.
      if (arguments.isNotEmpty) {
        final infos = [
          for (final argument in arguments) _typeInfo(argument, element),
        ];
        final isConst = infos.every((info) => info.$2);
        final whole = _type(
          type,
          element,
        ).rebuild((t) => t..isNullable = false);
        final described = literalList([for (final info in infos) info.$1]);
        return (
          isConst
              ? _spring('GenericType')
                    .constInstance([described], named, [whole])
              : _spring('GenericType').newInstance([described], named, [whole]),
          isConst,
        );
      }
      final self = _type(type, element).rebuild((t) => t..isNullable = false);
      if (type.element case final EnumElement enumElement) {
        // `@JsonValue` on a field or getter, or `@JsonProperty` names of
        // the constants.
        final jsonValue = enumJsonValue(
          enumElement,
          self,
          (parameters, body) => _closure(parameters, body, lambda: true),
        );
        final values = self.property('values');
        if (jsonValue == null) {
          return (
            _spring('EnumType').constInstance([values], named, [self]),
            true,
          );
        }
        return (
          _spring(
            'EnumType',
          ).newInstance([values], {...named, 'jsonValue': jsonValue}, [self]),
          false,
        );
      }
      return (_spring('ClassType').constInstance([], named, [self]), true);
    }
    if (type is VoidType) {
      return (_spring('DynamicType').constInstanceNamed('forVoid', []), true);
    }
    return (_spring('DynamicType').constInstance([]), true);
  }

  // Types described as `DynamicType`: `dynamic`, `Object`, functions,
  // records, type parameters (but captured ones).
  bool _isDynamicInfo(DartType type) => type is TypeParameterType
      ? !_captured.containsKey(type.element) && _erased[type.element] == null
      : type is! InterfaceType || type.isDartCoreObject;

  // `BeanMethod<T>('name', invoke: ..., annotations: [...])` for a method
  // with a `@BeanMethodAnnotation()` annotation.
  Expression _annotatedMethod(
    InterfaceType beanType,
    AnnotatedMethodModel method,
    Element element,
  ) => _spring('BeanMethod').newInstance(
    [_str(method.name)],
    {
      if (method.parameterTypes.isNotEmpty)
        'parameterTypes': literalConstList([
          for (final type in method.parameterTypes)
            type == null ? refer('Object') : _type(type, element),
        ]),
      'invoke': _closure(
        ['bean', 'arguments'],
        refer('Function')
            .property('apply')
            .call([refer('bean').property(method.name), refer('arguments')])
            .code,
        lambda: true,
      ),
      if (method.annotations.isNotEmpty)
        'annotations': literalConstList([
          for (final annotation in method.annotations)
            _constant(annotation, element),
        ]),
    },
    [_type(beanType, element)],
  );

