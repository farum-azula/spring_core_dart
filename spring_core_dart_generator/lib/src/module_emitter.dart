  // Profiles become a const `ProfileCondition`, condition types are
  // instantiated, condition annotations are re-created as constants.
  Expression _condition(ConditionModel condition, Element element) =>
      switch (condition) {
        ProfileConditionModel(:final profiles) =>
          _spring('ProfileCondition').constInstance([
            literalConstList([for (final p in profiles) _str(p)]),
          ]),
        TypeConditionModel(:final type) => _type(type, element).newInstance([]),
        AnnotationConditionModel(:final value) => _constant(value, element),
        GroupConditionModel(:final key, :final conditions) =>
          _spring('ConditionGroup').newInstance([
            _str(key),
            literalList([for (final c in conditions) _condition(c, element)]),
          ]),
      };

  // Declarative description of an injection point; the runtime uses it
  // to validate the bean graph at refresh (missing beans, cycles), not for
  // the lookup itself.
  Expression _dependency(InjectionPoint point, Element element) {
    final named = <String, Expression>{
      if (point.qualifier case final qualifier?) 'qualifier': _str(qualifier),
      if (point.optional || point.allowEmpty) 'optional': literalTrue,
    };
    final dependency = _spring('Dependency');
    return switch (point.kind) {
      PointKind.single when point.lazy != null => dependency.newInstanceNamed(
        'lazy',
        [_type(point.type, element)],
        {
          if (point.qualifier case final q?) 'qualifier': _str(q),
          if (point.name case final name?) 'name': _str(name),
        },
      ),
      PointKind.single => dependency.newInstance(
        [_type(point.type, element)],
        {...named, if (point.name case final name?) 'name': _str(name)},
      ),
      PointKind.list || PointKind.set => dependency.newInstanceNamed(
        'collection',
        [_type(point.type, element)],
        named,
      ),
      PointKind.map => dependency.newInstanceNamed('map', [
        _type(point.type, element),
      ], named),
      PointKind.provider => dependency.newInstanceNamed(
        'provider',
        [_type(point.type, element)],
        {if (point.qualifier case final q?) 'qualifier': _str(q)},
      ),
      PointKind.value => dependency.newInstanceNamed(
        'value',
        [_str(point.expression!)],
        {if (point.optional) 'optional': literalTrue},
      ),
    };
  }

  // Body of `create: (r) => ...`: a constructor call, a static method call
  // or a method call on the owner bean looked up by name.
  Expression _creation(BeanModel bean) {
    final creation = bean.creation;
    final (positional, named) = _arguments(creation.arguments, bean.element);
    switch (creation) {
      case ConstructorCreation(:final constructorName):
        final type = _type(bean.type, bean.element);
        return constructorName == null
            ? type.newInstance(positional, named)
            : type.newInstanceNamed(constructorName, positional, named);
      case BeanMethodCreation():
        final owner = creation.isStatic
            ? _type(creation.ownerType, bean.element)
            : refer('r')
                  .property('dependency')
                  .call(
                    [],
                    {'qualifier': _str(creation.ownerName)},
                    [_type(creation.ownerType, bean.element)],
                  );
        return owner.property(creation.methodName).call(positional, named);
      case InterfaceProxyCreation(:final model):
        return refer(model.className).property(r'$create').call([refer('r')]);
    }
  }

  // Splits arguments into positional and named resolver calls.
  (List<Expression>, Map<String, Expression>) _arguments(
    List<Argument> arguments,
    Element element,
  ) => (
    [
      for (final argument in arguments)
        if (argument.namedAs == null) _lookup(argument.point, element),
    ],
    {
      for (final argument in arguments)
        ?argument.namedAs: _lookup(argument.point, element),
    },
  );

  /// The resolver call that supplies [point].
  // Optional points use the `optional...` variants (returning `null`);
  // sets are built from the list lookup. A Dart default value or an
  // allowed-empty collection is applied with `??`.
  Expression _lookup(InjectionPoint point, Element element) {
    final lookup = _rawLookup(point, element);
    if (point.defaultValue case final value?) {
      return lookup.ifNullThen(_constant(value, element));
    }
    if (point.allowEmpty) {
      return lookup.ifNullThen(switch (point.kind) {
        PointKind.set => literalSet(const [], _type(point.type, element)),
        PointKind.map => literalMap(
          const {},
          refer('String'),
          _type(point.type, element),
        ),
        _ => literalList(const [], _type(point.type, element)),
      });
    }
    return lookup;
  }

  Expression _rawLookup(InjectionPoint point, Element element) {
    final r = refer('r');
    final type = _type(point.type, element);
    final qualifier = {if (point.qualifier case final q?) 'qualifier': _str(q)};
    final lenient = point.optional || point.allowEmpty;
    switch (point.kind) {
      case PointKind.single when point.lazy != null:
        return refer(point.lazy!.className).newInstance([
          r
              .property('lazyDependency')
              .call(
                [],
                {
                  ...qualifier,
                  if (point.name case final name?) 'name': _str(name),
                },
                [type],
              ),
        ]);
      case PointKind.single:
        return r
            .property(point.optional ? 'optionalDependency' : 'dependency')
            .call(
              [],
              {
                ...qualifier,
                if (point.name case final name?) 'name': _str(name),
              },
              [type],
            );
      case PointKind.list:
        return r
            .property(lenient ? 'optionalDependencyList' : 'dependencyList')
            .call([], qualifier, [type]);
      case PointKind.set:
        final list = r
            .property(lenient ? 'optionalDependencyList' : 'dependencyList')
            .call([], qualifier, [type]);
        return (lenient
                ? list.nullSafeProperty('toSet')
                : list.property('toSet'))
            .call([]);
      case PointKind.map:
        return r
            .property(lenient ? 'optionalDependencyMap' : 'dependencyMap')
            .call([], qualifier, [type]);
      case PointKind.provider:
        return r.property('provider').call([], qualifier, [type]);
      case PointKind.value:
        return r
            .property(point.optional ? 'optionalValue' : 'value')
            .call([_str(point.expression!)], {}, [type]);
    }
  }

  Expression _listener(
    InterfaceType beanType,
    ListenerModel listener,
    Element element,
  ) {
    final bean = _type(beanType, element);
    final parameter = listener.parameterType;
    final named = <String, Expression>{
      if (listener.order case final order?) 'order': literalNum(order),
    };
    // Common case: one event type equal to the parameter type, so the
    // runtime can check the type itself (`EventListenerMethod.of<B, E>`).
    if (listener.eventTypes.length == 1 &&
        parameter != null &&
        listener.eventTypes.single == parameter) {
      final eventType = _type(parameter, element);
      final handler = Method(
        (m) => m
          ..requiredParameters.addAll([
            Parameter((p) => p..name = 'bean'),
            Parameter((p) => p..name = 'event'),
          ])
          ..lambda = listener.returnsValue
          ..body = listener.returnsValue
              ? refer('bean')
                    .property(listener.methodName)
                    .call([refer('event')])
                    .code
              : Block.of([
                  refer('bean')
                      .property(listener.methodName)
                      .call([refer('event')])
                      .statement,
                  literalNull.returned.statement,
                ]),
      ).closure;
      return _spring('EventListenerMethod').property('of').call(
        [_str(listener.id), handler],
        {
          ...named,
          if (listener.condition case final condition?)
            'condition': _functionReference(condition, element),
        },
        [bean, eventType],
      );
    }

    // Several event types (and/or a parameterless method).
    final accepts = listener.eventTypes
        .map((t) => refer('candidate').isA(_type(t, element)))
        .reduce((a, b) => a.or(b));
    final acceptsFn = _closure(['candidate'], accepts.code, lambda: true);
    final matched = _spring('EventListenerMethod')
        .property('match')
        .call([refer('event'), acceptsFn]);
    final argument = parameter == null
        ? matched
        : matched.asA(_type(parameter, element));
    final handler = Method(
      (m) => m
        ..requiredParameters.addAll([
          Parameter((p) => p..name = 'bean'),
          Parameter((p) => p..name = 'event'),
        ])
        ..body = Block.of([
          if (listener.returnsValue)
            refer('bean')
                .property(listener.methodName)
                .call([if (parameter != null) argument])
                .returned
                .statement
          else ...[
            refer('bean')
                .property(listener.methodName)
                .call([if (parameter != null) argument])
                .statement,
            literalNull.returned.statement,
          ],
        ]),
    ).closure;
    final listenerType = TypeReference(
      (t) => t
        ..symbol = 'EventListenerMethod'
        ..url = _springUrl
        ..types.add(bean),
    );
    return listenerType.newInstanceNamed('matching', [], {
      'id': _str(listener.id),
      'accepts': acceptsFn,
      'invoke': handler,
      ...named,
      if (listener.condition case final condition?)
        'condition': _functionReference(condition, element),
    });
  }

  // An untyped closure; parameter types are inferred from the runtime
  // API's function types.
  Expression _closure(
    List<String> parameters,
    Code body, {
    bool lambda = false,
  }) => Method(
    (m) => m
      ..requiredParameters.addAll([
        for (final name in parameters) Parameter((p) => p..name = name),
      ])
      ..lambda = lambda
      ..body = body,
  ).closure;

  // A tear-off of a top-level function or `Class.staticMethod`.
  Expression _functionReference(ExecutableElement function, Element element) {
    final name = function.name!;
    final url = _importUrl(function.library.uri, element);
    final enclosing = function.enclosingElement;
    if (function is MethodElement && enclosing is InterfaceElement) {
      return refer(enclosing.name!, url).property(name);
    }
    return refer(name, url);
  }

  /// Re-creates a constant value (an annotation instance) as code.
  Expression _constant(DartObject value, Element element) {
    final reader = ConstantReader(value);
    if (reader.isNull) {
      return literalNull;
    }
    if (reader.isBool) {
      return literalBool(reader.boolValue);
    }
    if (reader.isInt) {
      return literalNum(reader.intValue);
    }
    if (reader.isDouble) {
      return literalNum(reader.doubleValue);
    }
    if (reader.isString) {
      return _str(reader.stringValue);
    }
    if (reader.isType) {
      return _type(reader.typeValue, element);
    }
    if (reader.isList) {
      return literalConstList([
        for (final item in reader.listValue) _constant(item, element),
      ]);
    }
    if (reader.isSet) {
      return literalConstSet({
        for (final item in reader.setValue) _constant(item, element),
      });
    }
    if (reader.isMap) {
      return literalConstMap({
        for (final MapEntry(:key, :value) in reader.mapValue.entries)
          _constant(key!, element): _constant(value!, element),
      });
    }
    final function = value.toFunctionValue();
    if (function != null) {
      return _functionReference(function, element);
    }
    // Any other object is "revived": source_gen finds a public const
    // constructor invocation (or a top-level constant / enum value) that
    // recreates it, which is written as `const Type(...)` with recursively
    // re-created arguments.
    final revivable = reader.revive();
    if (revivable.isPrivate) {
      throw InvalidGenerationSource(
        'Cannot re-create private constant ${value.type}.',
        element: element,
      );
    }
    final source = revivable.source;
    final url = _importUrl(source.removeFragment(), element);
    if (source.fragment.isEmpty) {
      // A top-level constant or an enum value (`Enum.value`).
      final [first, ...rest] = revivable.accessor.split('.');
      return rest.fold<Expression>(refer(first, url), (e, n) => e.property(n));
    }
    final type = refer(source.fragment, url);
    final positional = [
      for (final argument in revivable.positionalArguments)
        _constant(argument, element),
    ];
    final named = {
      for (final MapEntry(:key, :value) in revivable.namedArguments.entries)
        key: _constant(value, element),
    };
    return revivable.accessor.isEmpty
        ? type.constInstance(positional, named)
        : type.constInstanceNamed(revivable.accessor, positional, named);
  }

  // A reference to a class type (with type arguments and nullability),
  // `void`, `dynamic` or `Never`; other types are not supported here (use
  // `_anyType`).
  TypeReference _type(DartType type, Element element) {
    if (type is VoidType || type is DynamicType || type is NeverType) {
      return TypeReference((t) => t..symbol = type.getDisplayString());
    }
    if (type is! InterfaceType) {
      throw InvalidGenerationSource(
        'Unsupported type ${type.getDisplayString()}.',
        element: element,
      );
    }
    return TypeReference(
      (t) => t
        ..symbol = type.element.name
        ..url = _importUrl(
          type.element.library.uri,
          element,
          name: type.element.name,
        )
        ..isNullable = type.nullabilitySuffix == NullabilitySuffix.question
        ..types.addAll([
          // Type arguments may be type parameters, functions or records.
          for (final argument in type.typeArguments)
            _anyType(argument, element),
        ]),
    );
  }

  // Maps a library URI to an import usable from [output]: `dart:core`
  // needs none, runtime `src/` libraries map to the public library,
  // `package:` and `dart:` URIs are kept, `asset:` URIs under `lib/` become
  // `package:` URIs and other files of the same package (e.g. `test/`)
  // become relative paths. Anything else cannot be imported.
  String? _importUrl(Uri uri, Element element, {String? name}) {
    switch (uri.scheme) {
      case 'dart' when uri.path == 'core':
        return null;
      // `HttpClient` is declared in `dart:_http`, which cannot be imported:
      // use the public library the user's code imports it from (`dart:io`).
      case 'dart' when uri.path.startsWith('_'):
        final public = name == null ? null : publicSdkLibrary(name, element);
        if (public != null) {
          return public.path == 'core' ? null : public.toString();
        }
        throw InvalidGenerationSource(
          'Cannot reference ${name ?? 'a declaration'} of the internal '
          'library $uri: import the public library that exports it '
          '(for example dart:io) in the file that uses it.',
          element: element,
        );
      case 'package' when uri.pathSegments.first == 'spring_core_dart':
        // Public library instead of the runtime's src/ files.
        return _springUrl;
      case 'dart' || 'package':
        return uri.toString();
      case 'asset':
        final [package, ...segments] = uri.pathSegments;
        if (segments.firstOrNull == 'lib') {
          return _importUrl(
            Uri(
              scheme: 'package',
              pathSegments: [package, ...segments.skip(1)],
            ),
            element,
          );
        }
        if (package != output.package) {
          break;
        }
        return p.url.relative(
          p.url.joinAll(segments),
          from: p.url.dirname(output.path),
        );
    }
    throw InvalidGenerationSource(
      'Cannot import $uri from ${output.uri}.',
      element: element,
    );
  }
