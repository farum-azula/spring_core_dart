-- What the level 4 tests of spring_boot_starter_supabase need in a
-- project: the tables of the test application (test/app/supabase_app.dart)
-- with row-level security, a database function, the tables Realtime
-- reports, and a bucket with policies. The same shape as
-- test/postgrest/init.sql, with the project's own auth.uid().
--
-- Every grant is written out: a project no longer exposes new tables to
-- the API roles by itself, and an older one exposes them to `anon` too.

-- ---------------------------------------------------------------- todos

create table public.todos (
  id bigint generated by default as identity primary key,
  title text not null,
  list_id text not null,
  done boolean not null default false,
  priority text not null default 'low',
  created_at timestamptz,
  version integer,
  owner uuid not null default auth.uid()
);

alter table public.todos enable row level security;

create policy stack_own_todos on public.todos
  for all to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid()));

revoke all on public.todos from anon;
grant select, insert, update, delete on public.todos
  to authenticated, service_role;

-- ---------------------------------------------------------------- notes

create table public.notes (
  id text primary key,
  text text not null
);

alter table public.notes enable row level security;

create policy stack_notes on public.notes
  for all to authenticated
  using (true)
  with check (true);

revoke all on public.notes from anon;
grant select, insert, update, delete on public.notes
  to authenticated, service_role;

-- ------------------------------------------------------------- messages
-- The table of `Room.messages` (@PostgresChanges(table: 'messages',
-- filter: 'room_id=eq.{id}')): every signed-in user reads every message
-- and writes their own.

create table public.messages (
  id bigint generated by default as identity primary key,
  room_id text not null,
  body text not null,
  owner uuid not null default auth.uid()
);

alter table public.messages enable row level security;

create policy stack_messages_read on public.messages
  for select to authenticated
  using (true);

create policy stack_messages_write on public.messages
  for insert to authenticated
  with check (owner = (select auth.uid()));

create policy stack_messages_delete on public.messages
  for delete to authenticated
  using (owner = (select auth.uid()));

revoke all on public.messages from anon;
grant select, insert, delete on public.messages
  to authenticated, service_role;

-- ------------------------------------------------------------ functions
-- `Todos.closeAll` (@Procedure('close_all')): the rows it closes are the
-- caller's, since it runs with the caller's rights.

create function public.close_all(list_id text) returns integer
language sql
set search_path = ''
as $$
  with closed as (
    update public.todos set done = true
    where todos.list_id = close_all.list_id and not done
    returning 1
  )
  select count(*)::integer from closed
$$;

revoke all on function public.close_all(text) from public, anon;
grant execute on function public.close_all(text)
  to authenticated, service_role;

-- ------------------------------------------------------------- Realtime
-- A table is reported only when it is in this publication.

do $$
begin
  if not exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    create publication supabase_realtime;
  end if;
end
$$;

alter publication supabase_realtime add table public.todos, public.messages;

-- -------------------------------------------------------------- Storage
-- The bucket of `Avatars` (@StorageBucket('avatars')): public, so its
-- public URLs open; a user reads and writes only under the folder named
-- after their id (`<auth.uid()>/...`).

insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

create policy stack_avatars_read on storage.objects
  for select to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy stack_avatars_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy stack_avatars_update on storage.objects
  for update to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy stack_avatars_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

-- ------------------------------------------------------------- SQL path
-- spring.supabase.db.rls: user becomes `authenticated` or `anon` on the
-- connection of SUPABASE_DB_URL: its user must be a member of both. In a
-- project `postgres` is; this only makes sure, and never fails the
-- migration.

do $$
begin
  execute format('grant anon, authenticated to %I', current_user);
exception when others then
  raise notice 'anon and authenticated not granted to %: %',
    current_user, sqlerrm;
end
$$;
